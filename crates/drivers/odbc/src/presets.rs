//! One entry per engine served through ODBC. They share the session code
//! and differ in the connection-string template, the SQL dialect details
//! (quoting, row limit, batching) and a few catalog queries.

use dbine_driver::sql::Quote;
use dbine_driver::Family;

/// A value in the connection-string template.
#[derive(Debug, Clone, Copy)]
pub enum V {
    /// `{driver name}`.
    Driver,
    Host,
    Port,
    /// `host:port`.
    HostPort,
    Database,
    User,
    Password,
    /// A preset-specific option (`cfg.option(key)`).
    Opt(&'static str),
    Lit(&'static str),
    /// `5.0` when the driver is FreeTDS (Sybase ASE speaks TDS 5.0).
    FreeTdsVersion,
    /// Simba/Cloudera AuthMech: 3 user+password, 2 user only, 0 none.
    SimbaAuthMech,
    /// A value built from `{host}`, `{port}`, `{database}`, `{user}` and
    /// `{opt:key}`, written as is (Ingres vnodes, NuoDB `db@host:port`…).
    Fmt(&'static str),
    /// A preset option, or this default when it's empty.
    OptOr(&'static str, &'static str),
}

/// How a script is sent to the server.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Batch {
    /// One `SQLExecDirect` per statement, split on `;`.
    Statements,
    /// Blocks separated by `GO` lines (T-SQL style), each sent whole.
    Go,
    /// The whole text in one call.
    Script,
}

impl Batch {
    pub fn from_option(v: &str) -> Option<Batch> {
        match v {
            "statements" => Some(Batch::Statements),
            "go" => Some(Batch::Go),
            "script" => Some(Batch::Script),
            _ => None,
        }
    }
}

/// How the first rows of a table are asked for.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LimitStyle {
    /// `… LIMIT n`
    Limit,
    /// `SELECT TOP n …` (Sybase, SQL Anywhere, Teradata).
    Top,
    /// `… FETCH FIRST n ROWS ONLY` (DB2, Oracle-like).
    FetchFirst,
    /// `SELECT FIRST n …` (Informix, GBase 8s).
    First,
}

/// A parameter of a definition query.
#[derive(Debug, Clone, Copy)]
pub enum P {
    Schema,
    Name,
    /// The session's database (catalog).
    Catalog,
    /// `schema.name` (or just the name), unquoted.
    Qualified,
}

/// Where an object's source comes from.
#[derive(Debug, Clone, Copy)]
pub enum Def {
    None,
    /// A query with `?` parameters; its rows' first column, joined.
    Sql(&'static str, &'static [P], &'static str),
    /// `<prefix> schema.name` with quoted identifiers (Hive, Teradata);
    /// rows joined with newlines.
    Show(&'static str),
}

#[derive(Debug, Clone, Copy)]
pub struct Defs {
    pub table: Def,
    pub view: Def,
    pub procedure: Def,
    pub function: Def,
}

const NO_DEFS: Defs = Defs { table: Def::None, view: Def::None, procedure: Def::None, function: Def::None };

#[derive(Debug)]
pub struct Preset {
    pub id: &'static str,
    pub name: &'static str,
    pub family: Family,
    pub dialect: &'static str,
    pub default_port: u16,
    /// `None`: ask the driver (SQL_IDENTIFIER_QUOTE_CHAR).
    pub quote: Option<Quote>,
    /// `None`: guess from the DBMS name.
    pub limit: Option<LimitStyle>,
    pub driver_hint: &'static str,
    pub driver_help: &'static str,
    /// Connection-string attributes; empty ones are left out.
    pub template: &'static [(&'static str, V)],
    /// Label of the database form field (when the template uses it).
    pub database_label: &'static str,
    pub database_required: bool,
    /// Extra text options: (key, label, placeholder, required, help).
    pub extra_options: &'static [(&'static str, &'static str, &'static str, bool, &'static str)],
    /// Several databases per server: the explorer lists them.
    pub databases_label: &'static str,
    /// The query that lists them (else SQLTables for catalogs).
    pub databases_sql: Option<&'static str>,
    pub has_schemas: bool,
    pub procedures: bool,
    pub functions: bool,
    /// Schemas hidden from the explorer; `X*` is a prefix, case-insensitive.
    pub system_schemas: &'static [&'static str],
    pub batch: Batch,
    pub defs: Defs,
}

impl Preset {
    pub fn is_generic(&self) -> bool {
        self.id == "odbc"
    }

    /// The "database" is a local file or folder (Access, dBase).
    pub fn database_file(&self) -> bool {
        matches!(self.id, "access" | "dbase")
    }

    /// The template uses a `{placeholder}` of [`V::Fmt`] or one of these values.
    pub fn uses_part(&self, v: fn(&V) -> bool, placeholder: &str) -> bool {
        self.template.iter().any(|(_, x)| v(x) || matches!(x, V::Fmt(f) if f.contains(placeholder)))
    }

    pub fn uses(&self, v: fn(&V) -> bool) -> bool {
        self.template.iter().any(|(_, x)| v(x))
    }

    pub fn is_system_schema(&self, schema: &str) -> bool {
        self.system_schemas.iter().any(|p| match p.strip_suffix('*') {
            Some(prefix) => schema.len() >= prefix.len() && schema[..prefix.len()].eq_ignore_ascii_case(prefix),
            None => schema.eq_ignore_ascii_case(p),
        })
    }
}

