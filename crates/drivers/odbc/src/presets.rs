#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ids_are_unique_and_lowercase() {
        let mut ids: Vec<_> = PRESETS.iter().map(|p| p.id).collect();
        assert!(ids.iter().all(|i| i.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-')));
        let n = ids.len();
        ids.sort();
        ids.dedup();
        assert_eq!(ids.len(), n);
    }

    #[test]
    fn system_schemas_match_prefixes() {
        let db2 = PRESETS.iter().find(|p| p.id == "db2").unwrap();
        assert!(db2.is_system_schema("SYSIBM"));
        assert!(db2.is_system_schema("syscat"));
        assert!(!db2.is_system_schema("APP"));
        let generic = PRESETS.iter().find(|p| p.id == "odbc").unwrap();
        assert!(generic.is_system_schema("sys"));
        assert!(!generic.is_system_schema("dbo"));
    }
}
