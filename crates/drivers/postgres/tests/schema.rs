/// Identity columns keep ALWAYS and their sequence options through
/// `database_schema` + `table_ddl`.
#[tokio::test]
#[ignore]
async fn postgres_identity_options_round_trip() {
    let Ok(url) = std::env::var("DBINE_TEST_POSTGRES_URL") else {
        eprintln!("DBINE_TEST_POSTGRES_URL not set; skipping");
        return;
    };
    let cfg = parse_url("postgres", &url);
    let d = driver("postgres");
    let mut admin = d.connect(&cfg, None).await.expect("connect");
    for db in ["dbine_ident_src", "dbine_ident_dst"] {
        let _ = admin.drop_database(db).await;
        admin.create_database(db).await.expect("create_database");
    }
    let mut src = d.connect(&cfg, Some("dbine_ident_src")).await.unwrap();
    run(
        &mut src,
        "CREATE TABLE contadores (
            id int GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 5) PRIMARY KEY,
            ronda smallint GENERATED ALWAYS AS IDENTITY (MINVALUE 10 MAXVALUE 50 CACHE 3 CYCLE),
            plano bigint GENERATED BY DEFAULT AS IDENTITY,
            baja integer GENERATED ALWAYS AS IDENTITY (INCREMENT BY -1),
            viejo serial
        );
        ALTER SEQUENCE contadores_viejo_seq RESTART WITH 1 START WITH 7;",
    )
    .await;
    let schema = src.database_schema().await.unwrap();
    let t = schema.iter().find(|t| t.name == "contadores").unwrap();
    let opt = |i: usize| t.columns[i].options.get("identity").cloned();
    assert_eq!(opt(0).as_deref(), Some("BY DEFAULT (START WITH 100 INCREMENT BY 5)"));
    assert_eq!(opt(1).as_deref(), Some("ALWAYS (MINVALUE 10 MAXVALUE 50 CACHE 3 CYCLE)"));
    assert_eq!(opt(2), None);
    assert_eq!(opt(3).as_deref(), Some("ALWAYS (INCREMENT BY -1)"));
    assert_eq!(opt(4).as_deref(), Some("BY DEFAULT (START WITH 7)"));

    let ddl = d.table_ddl(t, DdlParts { create: true, indexes: true, foreign_keys: true, ..Default::default() }).unwrap();
    eprintln!("{ddl}");
    assert!(ddl.contains("\"id\" integer GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 5) NOT NULL"), "{ddl}");
    assert!(ddl.contains("\"ronda\" smallint GENERATED ALWAYS AS IDENTITY (MINVALUE 10 MAXVALUE 50 CACHE 3 CYCLE) NOT NULL"), "{ddl}");
    assert!(ddl.contains("\"plano\" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL"), "{ddl}");

    let mut dst = d.connect(&cfg, Some("dbine_ident_dst")).await.unwrap();
    run(&mut dst, &ddl).await;
    let copy = dst.database_schema().await.unwrap();
    assert_eq!(copy, schema);
    run(&mut dst, "INSERT INTO contadores DEFAULT VALUES; INSERT INTO contadores DEFAULT VALUES;").await;
    let mut out = QueryOutcome::default();
    dst.execute("SELECT max(id), max(ronda), min(baja), max(viejo) FROM contadores", 10, &mut out).await.unwrap();
    assert_eq!(out.results[0].rows[0], vec![json!("105"), json!("11"), json!("-2"), json!("8")]);

    drop((src, dst));
    for db in ["dbine_ident_src", "dbine_ident_dst"] {
        admin.drop_database(db).await.expect("drop_database");
    }
}

