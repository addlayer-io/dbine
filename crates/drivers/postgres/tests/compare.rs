///
/// ```sh
/// DBINE_TEST_RISINGWAVE_URL=postgres://root@localhost:25042/dev \
///   cargo test -p dbine-driver-postgres --test compare risingwave -- --ignored --nocapture
/// ```
#[tokio::test]
#[ignore]
async fn risingwave() {
    let Ok(url) = std::env::var("DBINE_TEST_RISINGWAVE_URL") else {
        eprintln!("DBINE_TEST_RISINGWAVE_URL not set; skipping");
        return;
    };
    let table = "CREATE SCHEMA app;\nCREATE TABLE app.docs (id int PRIMARY KEY, a int, b varchar, c varchar);\n";
    let source = format!(
        "{table}CREATE INDEX docs_ix ON app.docs (a DESC, b) INCLUDE (c);\nCREATE INDEX docs_ix2 ON app.docs (lower(b)) DISTRIBUTED BY (lower(b));\nCREATE INDEX docs_todo ON app.docs (c);\n"
    );
    let target = format!("{table}CREATE INDEX docs_ix ON app.docs (a);\n");
    let got = compare_and_sync("risingwave", &url, &source, &target, |ta, _| {
        let docs = &ta["docs"];
        let i = ix(docs, "docs_ix");
        assert_eq!((i.include.as_slice(), i.options.get("keys").map(String::as_str)), (&["c".to_string()][..], Some("a DESC, b")));
        assert_eq!(ix(docs, "docs_ix2").options.get("distributed_by").map(String::as_str), Some("lower(b)"));
        assert!(ix(docs, "docs_todo").include.is_empty());
    })
    .await;
    assert!(got.is_empty());
}

