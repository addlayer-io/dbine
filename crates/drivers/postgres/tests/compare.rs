//! "Comparar esquemas" against real servers: two databases that differ in
//! every kind of thing the compare reads (CHECK, INCLUDE / STORING, index
//! methods, sort orders and operator classes, expression and full-text
//! indexes, storage parameters, NULLS NOT DISTINCT, UNIQUE and EXCLUDE
//! constraints, sequences, enums, domains, composite and range types). The
//! sync script is run on one side and both must then read the same.
//!
//! ```sh
//! DBINE_TEST_POSTGRES_URL=postgres://postgres:pw@localhost:25010/postgres \
//! DBINE_TEST_COCKROACH_URL=postgres://root@localhost:26014/defaultdb \
//!   cargo test -p dbine-driver-postgres --test compare -- --ignored --nocapture
//! ```
//!
//! `DBINE_TEST_TIMESCALE_URL` and `DBINE_TEST_YUGABYTE_URL` run the same
//! checks on TimescaleDB and YugabyteDB.

use dbine_driver::{ConnectionConfig, Driver, ObjectRef, QueryOutcome, Session, TableChange, TableSchema};
use std::collections::BTreeMap;
use std::sync::Arc;

fn parse_url(driver: &str, url: &str) -> ConnectionConfig {
    let rest = url.split_once("://").map_or(url, |(_, r)| r);
    let (auth, hostpart) = rest.rsplit_once('@').unwrap_or(("", rest));
    let (user, pass) = auth.split_once(':').map_or((auth, None), |(u, p)| (u, Some(p)));
    let (hostport, db) = hostpart.split_once('/').unwrap_or((hostpart, ""));
    let (host, port) = hostport.rsplit_once(':').map_or((hostport, 0), |(h, p)| (h, p.parse().unwrap()));
    ConnectionConfig {
        driver: driver.into(),
        host: host.into(),
        port,
        database: db.into(),
        username: (!user.is_empty()).then(|| user.into()),
        password: pass.map(Into::into),
        ..Default::default()
    }
}

fn driver(id: &str) -> Arc<dyn Driver> {
    dbine_driver_postgres::drivers().into_iter().find(|d| d.info().id == id).unwrap()
}

async fn run(s: &mut Box<dyn Session>, sql: &str) -> Result<(), String> {
    let mut out = QueryOutcome::default();
    s.execute(sql, 100, &mut out).await.map_err(|e| e.to_string())?;
    match out.error.take() {
        Some(e) => Err(e),
        None => Ok(()),
    }
}

/// One statement at a time (CockroachDB won't use a type in the
/// transaction that made it).
async fn run_all(s: &mut Box<dyn Session>, script: &str) {
    for stmt in script.split(";\n").map(str::trim).filter(|s| !s.is_empty()) {
        run(s, stmt).await.unwrap_or_else(|e| panic!("{e}\n---\n{stmt}"));
    }
}

