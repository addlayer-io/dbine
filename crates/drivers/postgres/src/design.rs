        assert!(s.ends_with("ALTER TABLE \"app\".\"pedidos\" ADD CONSTRAINT \"pedidos_cliente_fk\" FOREIGN KEY (\"cliente_id\") REFERENCES \"app\".\"clientes\" (\"id\") ON DELETE CASCADE;"));
