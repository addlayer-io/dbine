    #[test]
    fn update_script_escapes_quotes_and_redshift_backslashes() {
        let c = RowChange {
            key: vec![("id".into(), json!(7)), ("region".into(), Value::Null)],
            set: vec![("nombre".into(), json!("O'Brien\\x")), ("baja".into(), Value::Null)], ..Default::default()
        };
        assert_eq!(
            update_script(Variant::Postgres, Some("public"), "clientes", std::slice::from_ref(&c)),
            "UPDATE \"public\".\"clientes\" SET \"nombre\" = 'O''Brien\\x', \"baja\" = NULL WHERE \"id\" = 7 AND \"region\" IS NULL;"
        );
        assert_eq!(
            update_script(Variant::Redshift, Some("public"), "clientes", &[c]),
            "UPDATE \"public\".\"clientes\" SET \"nombre\" = 'O''Brien\\\\x', \"baja\" = NULL WHERE \"id\" = 7 AND \"region\" IS NULL;"
        );
    }

