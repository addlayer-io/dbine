    #[test]
    fn identity_options_from_the_catalog() {
        let max = i64::MAX as i128;
        // Defaults stay implicit.
        assert_eq!(identity_option(false, "bigint", 1, 1, 1, max, 1, false), None);
        assert_eq!(identity_option(true, "bigint", 1, 1, 1, max, 1, false).as_deref(), Some("ALWAYS"));
        assert_eq!(
            identity_option(false, "integer", 100, 5, 1, i32::MAX.into(), 1, false).as_deref(),
            Some("BY DEFAULT (START WITH 100 INCREMENT BY 5)")
        );
        assert_eq!(
            identity_option(true, "smallint", 10, 1, 10, 500, 20, true).as_deref(),
            Some("ALWAYS (MINVALUE 10 MAXVALUE 500 CACHE 20 CYCLE)")
        );
        // Descending: starts at -1 by default, the type's minimum.
        assert_eq!(identity_option(false, "integer", -1, -1, i32::MIN.into(), -1, 1, false).as_deref(), Some("BY DEFAULT (INCREMENT BY -1)"));
    }

    #[test]
    fn identity_options_in_the_ddl() {
        let mut t = sample();
        t.columns[0].options.insert(IDENTITY_OPTION.into(), "BY DEFAULT (START WITH 100 INCREMENT BY 5)".into());
        let s = table_ddl(Variant::Postgres, &t, ALL);
        assert!(s.contains("\n    \"id\" bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 5) NOT NULL,"), "{s}");
        t.columns[0].options.insert(IDENTITY_OPTION.into(), "ALWAYS (MINVALUE 10 MAXVALUE 500 CACHE 20 CYCLE)".into());
        for v in [Variant::Postgres, Variant::Timescale, Variant::Yugabyte, Variant::AlloyDb] {
            let s = table_ddl(v, &t, ALL);
            assert!(s.contains("\"id\" bigint GENERATED ALWAYS AS IDENTITY (MINVALUE 10 MAXVALUE 500 CACHE 20 CYCLE) NOT NULL,"), "{v:?}: {s}");
        }
        // ADD COLUMN in a sync script too.
        let f = flavor(Variant::Postgres);
        assert_eq!(column_def(Variant::Postgres, &f, &t, &t.columns[0]), "\"id\" bigint GENERATED ALWAYS AS IDENTITY (MINVALUE 10 MAXVALUE 500 CACHE 20 CYCLE) NOT NULL");
        // Variants without these options keep what they wrote.
        assert!(table_ddl(Variant::Cockroach, &t, ALL).contains("\"id\" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,"));
        assert!(table_ddl(Variant::OpenGauss, &t, ALL).contains("\"id\" bigserial NOT NULL,"));
        assert!(table_ddl(Variant::Redshift, &t, ALL).contains("\"id\" bigint IDENTITY(1,1) NOT NULL"));
        // Only the recognized words make it into the DDL.
        for bad in ["ALWAYS; DROP TABLE x", "1000,5", "BY DEFAULT (START WITH 1 OWNED BY x.y)", "ALWAYS (CACHE)"] {
            t.columns[0].options.insert(IDENTITY_OPTION.into(), bad.into());
            assert!(table_ddl(Variant::Postgres, &t, ALL).contains("\"id\" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,"), "{bad}");
        }
        assert_eq!(identity_clause("always (start 3 increment -2 no cycle)").as_deref(), Some(" GENERATED ALWAYS AS IDENTITY (START WITH 3 INCREMENT BY -2 NO CYCLE)"));
    }

    #[test]
    fn if_exists_guards() {
        let s = table_ddl(Variant::Postgres, &sample(), DdlParts { if_exists: true, ..ALL });
        assert!(s.starts_with("CREATE TABLE IF NOT EXISTS \"app\".\"pedidos\""));
        assert!(s.contains("CREATE UNIQUE INDEX IF NOT EXISTS \"ux_email\""));
        assert!(s.contains("DO $$ BEGIN\n    ALTER TABLE"), "{s}");
        let c = table_ddl(Variant::Cockroach, &sample(), DdlParts { if_exists: true, foreign_keys: true, ..Default::default() });
        assert_eq!(c, "ALTER TABLE \"app\".\"pedidos\" ADD CONSTRAINT IF NOT EXISTS \"pedidos_cliente_fk\" FOREIGN KEY (\"cliente_id\") REFERENCES \"app\".\"clientes\" (\"id\") ON DELETE CASCADE;");
        let d = table_ddl(Variant::Postgres, &sample(), DdlParts { drop: true, if_exists: true, ..Default::default() });
        assert_eq!(d, "DROP TABLE IF EXISTS \"app\".\"pedidos\";");
    }

    #[test]
