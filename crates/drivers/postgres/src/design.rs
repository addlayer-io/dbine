//! The driver's side of the table structure per variant: capabilities,
//! the table designer, create templates and the DDL / INSERT scripts.

use crate::Variant;
use dbine_driver::ddl::{self, AutoIncrement, SqlFlavor};
use dbine_driver::sql::{qualified_name, quote_ident, Quote};
use dbine_driver::{kinds, Capabilities, CreateTemplate, DdlParts, DesignerSpec, Field, FieldKind, RowChange, TableSchema};
use serde_json::Value;

fn flavor(v: Variant) -> SqlFlavor {
    match v {
        Variant::Redshift => SqlFlavor { auto_increment: AutoIncrement::Identity, ..SqlFlavor::ansi() },
        // No identity columns, no COMMENT ON.
        Variant::CrateDb => SqlFlavor { auto_increment: AutoIncrement::None, comment_on: false, ..SqlFlavor::ansi() },
        Variant::RisingWave | Variant::Materialize => SqlFlavor { auto_increment: AutoIncrement::None, ..SqlFlavor::ansi() },
        _ => SqlFlavor::ansi(),
    }
}

/// The script that applies schema changes ("Comparar esquemas").
pub fn sync_script(v: Variant, changes: &[dbine_driver::TableChange]) -> dbine_driver::Result<dbine_driver::SyncScript> {
    use dbine_driver::alter::{AlterStyle, ColumnAlter};
    let column = match v {
        // Only varchar lengths change, and without USING.
        Variant::Redshift => ColumnAlter::Standard { set_data_type: false, using_cast: false },
        Variant::H2 => ColumnAlter::Standard { set_data_type: true, using_cast: false },
        // Columns can't change type.
        Variant::CrateDb | Variant::RisingWave | Variant::Materialize => ColumnAlter::None,
        _ => ColumnAlter::Standard { set_data_type: false, using_cast: true },
    };
    let f = flavor(v);
    let cd = |t: &TableSchema, c: &dbine_driver::ColumnDef| column_def(v, &f, t, c);
    let dd = |t: &TableSchema, p: DdlParts| Ok(table_ddl(v, t, p));
    let mut script = dbine_driver::alter::sync_script(&AlterStyle::from_flavor(&f, column, &cd, &dd), changes)?;
    crate::compare::fix_drops(v, &mut script.statements, changes);
    if v == Variant::CrateDb {
        crate::compare::crate_sync(&mut script, changes);
    }
    if v.streaming() {
        // A script of several statements runs as a transaction there, and
        // CREATE INDEX can't: one statement per chunk.
        script.statements = script
            .statements
            .iter()
            .flat_map(|s| s.split(";\n").map(|p| format!("{};", p.trim().trim_end_matches(';'))).collect::<Vec<_>>())
            .filter(|s| s != ";")
            .collect();
    }
    Ok(script)
}

/// [`dbine_driver::ColumnDef::options`] key: an identity column's
/// generation and sequence options when they aren't the defaults (read by
/// `database_schema`), as PostgreSQL writes them after `GENERATED`:
/// `ALWAYS` / `BY DEFAULT`, then `(START WITH 100 INCREMENT BY 5 …)`.
/// Same key as SQL Server's `IDENTITY(seed,increment)`.
pub(crate) const IDENTITY_OPTION: &str = "identity";

const BY_DEFAULT_IDENTITY: &str = " GENERATED BY DEFAULT AS IDENTITY";

/// Variants whose identity columns take ALWAYS and sequence options. Not
/// openGauss (serials), CockroachDB (its own identity reading) nor the
/// ones without identity columns.
fn identity_options(v: Variant) -> bool {
    flavor(v).auto_increment == AutoIncrement::GeneratedIdentity && !matches!(v, Variant::OpenGauss | Variant::Cockroach)
}

/// The identity option's value as ` GENERATED … AS IDENTITY (…)`, rebuilt
/// from the recognized words only; `None` if it isn't one.
fn identity_clause(value: &str) -> Option<String> {
    let spaced = value.replace(['(', ')', ','], " ").to_ascii_uppercase();
    let words: Vec<&str> = spaced.split_whitespace().collect();
    let mut i = 0;
    let how = match words.first().copied()? {
        "ALWAYS" => "ALWAYS",
        "BY" if words.get(1) == Some(&"DEFAULT") => {
            i = 1;
            "BY DEFAULT"
        }
        _ => return None,
    };
    i += 1;
    let num = |w: Option<&&str>| -> Option<String> {
        let w = *w?;
        let digits = w.strip_prefix('-').unwrap_or(w);
        (!digits.is_empty() && digits.chars().all(|c| c.is_ascii_digit())).then(|| w.to_string())
    };
    let mut opts: Vec<String> = Vec::new();
    while i < words.len() {
        let (text, used) = match words[i] {
            "START" | "INCREMENT" => {
                let (kw, filler) = if words[i] == "START" { ("START WITH", "WITH") } else { ("INCREMENT BY", "BY") };
                let skip = usize::from(words.get(i + 1) == Some(&filler));
                (format!("{kw} {}", num(words.get(i + 1 + skip))?), 2 + skip)
            }
            w @ ("MINVALUE" | "MAXVALUE" | "CACHE") => (format!("{w} {}", num(words.get(i + 1))?), 2),
            "CYCLE" => ("CYCLE".to_string(), 1),
            "NO" => match words.get(i + 1).copied()? {
                w @ ("CYCLE" | "MINVALUE" | "MAXVALUE") => (format!("NO {w}"), 2),
                _ => return None,
            },
            _ => return None,
        };
        opts.push(text);
        i += used;
    }
    let tail = if opts.is_empty() { String::new() } else { format!(" ({})", opts.join(" ")) };
    Some(format!(" GENERATED {how} AS IDENTITY{tail}"))
}

/// A column as CREATE TABLE / ADD COLUMN writes it, with its identity's
/// ALWAYS and sequence options ([`IDENTITY_OPTION`]).
fn column_def(v: Variant, f: &SqlFlavor, t: &TableSchema, c: &dbine_driver::ColumnDef) -> String {
    let line = ddl::column_def(f, t, c);
    if !c.auto_increment || !identity_options(v) {
        return line;
    }
    match c.options.get(IDENTITY_OPTION).and_then(|o| identity_clause(o)) {
        Some(clause) => line.replacen(BY_DEFAULT_IDENTITY, &clause, 1),
        None => line,
    }
}

/// The identity option for a column read from the catalog (`attidentity`
/// `a` / `d` and its sequence's `pg_sequence` row), `None` when everything
/// is the default (`BY DEFAULT`, start at the first value, step 1, the
/// type's range, cache 1, no cycle).
#[allow(clippy::too_many_arguments)]
pub(crate) fn identity_option(always: bool, type_name: &str, start: i128, increment: i128, min: i128, max: i128, cache: i128, cycle: bool) -> Option<String> {
    let (type_min, type_max): (i128, i128) = match type_name {
        "smallint" => (i16::MIN.into(), i16::MAX.into()),
        "integer" => (i32::MIN.into(), i32::MAX.into()),
        _ => (i64::MIN.into(), i64::MAX.into()),
    };
    let (default_min, default_max) = if increment > 0 { (1, type_max) } else { (type_min, -1) };
    let default_start = if increment > 0 { min } else { max };
    let mut opts: Vec<String> = Vec::new();
    if start != default_start {
        opts.push(format!("START WITH {start}"));
    }
    if increment != 1 {
        opts.push(format!("INCREMENT BY {increment}"));
    }
    if min != default_min {
        opts.push(format!("MINVALUE {min}"));
    }
    if max != default_max {
        opts.push(format!("MAXVALUE {max}"));
    }
    if cache != 1 {
        opts.push(format!("CACHE {cache}"));
    }
    if cycle {
        opts.push("CYCLE".into());
    }
    if !always && opts.is_empty() {
        return None;
    }
    let how = if always { "ALWAYS" } else { "BY DEFAULT" };
    Some(if opts.is_empty() { how.to_string() } else { format!("{how} ({})", opts.join(" ")) })
}

pub fn capabilities(v: Variant) -> Capabilities {
    let supported = crate::blocking::supported(v);
    Capabilities { blocking: supported, kill_session: supported, ..engine_capabilities(v) }
}

fn engine_capabilities(v: Variant) -> Capabilities {
    let all = Capabilities { create_database: true, drop_database: true, foreign_keys: true, monitor: true, ..Default::default() };
    match v {
        // A virtual layer: its databases and views are managed in Denodo.
        Variant::Denodo => Capabilities { monitor: true, ..Capabilities::default() },
        // One database per connection (a file), created on connect.
        Variant::H2 => Capabilities { create_database: false, drop_database: false, ..all },
        // One cluster-wide namespace of schemas; no foreign keys.
        Variant::CrateDb => Capabilities { create_database: false, drop_database: false, foreign_keys: false, monitor: true, ..Default::default() },
        // Greenplum (and its forks) parse FOREIGN KEY but don't keep it;
        // the streaming engines have no foreign keys at all.
        _ if v.mpp() || v.streaming() => Capabilities { foreign_keys: false, ..all },
        _ => all,
    }
}

