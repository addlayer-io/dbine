//! Bulk transfer (see `dbine_driver::transfer`).
//!
//! - Reading: one `SELECT` (only a `SELECT` runs on the source) fetched
//!   up to [`FETCH_ROWS`] rows, and about [`FETCH_BYTES`] by the columns'
//!   declared widths, per round trip, each value turned into its typed
//!   cell: integers → integer, `DECIMAL` / `SMALLDECIMAL` → exact decimal
//!   text, `REAL` / `DOUBLE` → float, character types and `CLOB` / `NCLOB`
//!   → text (whole), `VARBINARY` / `BLOB` → bytes (whole), `DATE` → date,
//!   `TIME` → time, `SECONDDATE` / `TIMESTAMP` → date-time (the timestamp's
//!   full 100 ns precision), `BOOLEAN` → boolean, `ST_GEOMETRY` / `ST_POINT`
//!   → their WKB (`ST_AsWKB()`) as bytes, the SRID in the type name.
//!   Text the client can't decode (`DBSTRING`) stops the read.
//! - Loading: one prepared `INSERT … VALUES (?, …)` whose parameter rows go
//!   in batches (the client's batch execute: [`BATCH_ROWS`] rows or
//!   [`BATCH_BYTES`] per round trip), with auto-commit off and a commit
//!   every `commit_rows` / `commit_bytes`; a session with auto-commit
//!   already off is refused (its open work would be committed or undone).
//!   Each value is bound with the type the server asks for the parameter,
//!   and a value the parameter can't hold as is stops the load: decimals
//!   past the precision or scale (the client would cut them, and HANA
//!   rounds a DECIMAL(p,s) described without FIXED types), REALs out of
//!   range or that don't read back as the same number, NaN and infinity (HANA
//!   has neither), decimal exponents past any DECIMAL, fractions of a
//!   second a TIME / SECONDDATE / TIMESTAMP can't keep, a time of day into
//!   a DATE and a date or zone into a TIME (as cells or as text), dates
//!   and times that don't exist in zoned values (the UTC conversion would
//!   roll them over), clocks HANA could read another way (`10:00 PM`,
//!   `10:00 UTC`), bytes
//!   that aren't UTF-8 into text. BLOB / CLOB / NCLOB values over
//!   [`LOB_INLINE`] bytes are streamed to the server (the row goes on its
//!   own). Spatial columns take WKB bytes (EWKB turned into ISO WKB, hex
//!   text decoded) or WKT / EWKT through `ST_GeomFromWKB` /
//!   `ST_GeomFromText` with the column's SRID; another SRID, or GeoJSON,
//!   is refused. With `table_lock`, each commit window starts with
//!   `LOCK TABLE … IN EXCLUSIVE MODE`.
//! - Identity columns: `GENERATED BY DEFAULT` accept the given values with
//!   `keep_identity`, and after the last commit the identity is moved past
//!   the largest key (`ALTER TABLE … ALTER (… GENERATED BY DEFAULT AS
//!   IDENTITY (START WITH n))`, DDL that HANA commits on its own; if it
//!   fails the load fails); `GENERATED ALWAYS` don't accept them, so
//!   the load stops and says so. Without `keep_identity` identity columns
//!   are left out and HANA generates them. Computed columns
//!   (`GENERATED ALWAYS AS <expr>`) are always left out.

use super::{err, iso, quote, HanaSession};
use dbine_driver::transfer::{BatchBuilder, BatchSinkRef, BatchSource, Cell, LoadSpec, Progress, ReadSpec, TransferColumn};
use dbine_driver::{Error, Result};
use hdbconnect_async::{FieldMetadata, HdbValue, ParameterDescriptor, TypeId};
use std::collections::HashMap;
use std::sync::Arc;

/// Most rows per fetch round trip…
const FETCH_ROWS: u32 = 32_768;
/// …and about this many bytes per fetch (by the columns' declared widths),
/// so wide rows don't fill hundreds of MB per round trip.
const FETCH_BYTES: usize = 4 * 1024 * 1024;
/// Bytes per LOB read round trip while reading whole LOBs.
const LOB_READ: u32 = 1024 * 1024;
/// Parameter rows per batch execute…
const BATCH_ROWS: usize = 10_000;
/// …or bytes of values, whichever comes first. Kept at 1 MiB (the usual
/// client packet size) so a request never grows past a few MiB.
const BATCH_BYTES: usize = 1024 * 1024;
/// Largest LOB value sent inline in a batch; larger ones are streamed.
const LOB_INLINE: usize = 512 * 1024;
/// Largest value sent whole in a request (parameters that can't be
/// streamed: TEXT, BINTEXT, character and binary types).
const INLINE_MAX: usize = 16 * 1024 * 1024;

// ---------------------------------------------------------------- reading

const READ_SRIDS: &str = "SELECT COLUMN_NAME, SRS_ID FROM SYS.ST_GEOMETRY_COLUMNS WHERE SCHEMA_NAME = ? AND TABLE_NAME = ?";

pub(crate) async fn read_batches(s: &mut HanaSession, spec: &ReadSpec, sink: BatchSinkRef) -> Result<u64> {
    let owner = s.owner(&spec.table);
    let table = format!("{}.{}", quote(&owner), quote(&spec.table.name));
    let cols = match &spec.columns {
        Some(c) if !c.is_empty() => c.iter().map(|c| quote(c)).collect::<Vec<_>>().join(", "),
        _ => "*".to_string(),
    };
    // Described first: spatial columns are read through an expression.
    let meta = s.conn.query(format!("SELECT {cols} FROM {table} WHERE 1 = 0")).await.map_err(err)?.metadata();
    // The spatial columns' SRIDs, for their type names (WKB carries none).
    let mut srids: HashMap<String, i64> = HashMap::new();
    if meta.iter().any(|m| matches!(m.type_id(), TypeId::GEOMETRY | TypeId::POINT)) {
        for r in s.rows(READ_SRIDS, &[&owner, &spec.table.name]).await? {
            if let (Some(col), Some(srid)) = (r.first().and_then(super::text), r.get(1).and_then(super::int)) {
                srids.insert(col, srid);
            }
        }
    }
    // Display names: the select list's names (aliases included), which is
    // what the generated `SELECT` quotes back.
    let columns: Vec<TransferColumn> = meta
        .iter()
        .map(|m| {
            let name = m.displayname().to_string();
            let mut type_name = type_name(m);
            if let Some(srid) = srids.get(&name) {
                type_name = format!("{type_name}({srid})");
            }
            TransferColumn { name, type_name, nullable: m.is_nullable() }
        })
        .collect();
    let select: Vec<String> = meta.iter().map(|m| read_expr(m.displayname(), m.type_id())).collect();
    let sql = select_sql(&select, &table, spec.filter.as_deref());
    let widths: Vec<usize> = meta.iter().map(|m| wire_width(m.type_id(), m.precision())).collect();

    let (fetch, lob) = (s.conn.fetch_size().await, s.conn.lob_read_length().await);
    s.conn.set_fetch_size(fetch_rows(&widths)).await;
    s.conn.set_lob_read_length(LOB_READ).await;
    let r = read(s, &sql, &columns, &sink).await;
    s.conn.set_fetch_size(fetch).await;
    s.conn.set_lob_read_length(lob).await;
    r
}

async fn read(s: &HanaSession, sql: &str, columns: &[TransferColumn], sink: &BatchSinkRef) -> Result<u64> {
    let lock_err = |_| Error::State("destino de lotes".into());
    sink.lock().map_err(lock_err)?.begin(columns)?;
    let mut rs = s.conn.query(sql).await.map_err(err)?;
    let mut builder = BatchBuilder::new();
    while let Some(row) = rs.next_row().await.map_err(err)? {
        let mut cells = Vec::with_capacity(row.len());
        for v in row {
            cells.push(to_cell(v).await?);
        }
        builder.push(cells, &mut *sink.lock().map_err(lock_err)?)?;
    }
    builder.flush(&mut *sink.lock().map_err(lock_err)?)?;
    Ok(builder.rows)
}

fn select_sql(select: &[String], table: &str, filter: Option<&str>) -> String {
    let mut sql = format!("SELECT {} FROM {table}", select.join(", "));
    if let Some(f) = filter.map(str::trim).filter(|f| !f.is_empty()) {
        sql.push_str(&format!(" WHERE {f}"));
    }
    sql
}

/// A column's largest size on the wire, by its declared width. LOBs travel
/// as a locator plus a first chunk; spatial values as their WKB.
fn wire_width(t: TypeId, precision: i16) -> usize {
    let len = usize::try_from(precision).unwrap_or(0).max(1);
    2 + match t {
        TypeId::TINYINT | TypeId::BOOLEAN => 1,
        TypeId::SMALLINT => 2,
        TypeId::INT | TypeId::REAL | TypeId::DAYDATE | TypeId::SECONDTIME => 4,
        TypeId::BIGINT | TypeId::DOUBLE | TypeId::LONGDATE | TypeId::SECONDDATE | TypeId::FIXED8 => 8,
        TypeId::FIXED12 => 12,
        TypeId::DECIMAL | TypeId::FIXED16 => 16,
        // CESU-8: up to 3 bytes a character.
        TypeId::CHAR | TypeId::VARCHAR | TypeId::NCHAR | TypeId::NVARCHAR | TypeId::STRING | TypeId::NSTRING | TypeId::ALPHANUM | TypeId::SHORTTEXT => {
            3 * len
        }
        TypeId::BINARY | TypeId::VARBINARY | TypeId::BSTRING => len,
        TypeId::CLOB | TypeId::NCLOB | TypeId::TEXT | TypeId::BINTEXT | TypeId::BLOB | TypeId::BLOCATOR => 4096,
        TypeId::GEOMETRY | TypeId::POINT => 4096,
    }
}

/// Rows per fetch so a fetch stays near [`FETCH_BYTES`].
fn fetch_rows(widths: &[usize]) -> u32 {
    let row: usize = widths.iter().sum::<usize>().max(1);
    u32::try_from(FETCH_BYTES / row).unwrap_or(FETCH_ROWS).clamp(1, FETCH_ROWS)
}

/// The select-list item of a column: spatial values as their WKB.
fn read_expr(name: &str, t: TypeId) -> String {
    let q = quote(name);
    match t {
        TypeId::GEOMETRY | TypeId::POINT => format!("{q}.ST_AsWKB() AS {q}"),
        _ => q,
    }
}

/// The column's type as HANA spells it.
fn type_name(m: &FieldMetadata) -> String {
    type_name_of(m.type_id(), m.precision(), m.scale())
}

fn type_name_of(t: TypeId, precision: i16, scale: i16) -> String {
    let sized = |name: &str| if precision > 0 { format!("{name}({precision})") } else { name.to_string() };
    match t {
        TypeId::TINYINT => "TINYINT".into(),
        TypeId::SMALLINT => "SMALLINT".into(),
        TypeId::INT => "INTEGER".into(),
        TypeId::BIGINT => "BIGINT".into(),
        TypeId::DECIMAL | TypeId::FIXED8 | TypeId::FIXED12 | TypeId::FIXED16 => {
            // Floating decimals (DECIMAL without precision, SMALLDECIMAL)
            // report a scale outside 0..=precision; SMALLDECIMAL's
            // precision is 16, DECIMAL's 34.
            if precision > 0 && (0..=precision).contains(&scale) {
                format!("DECIMAL({precision},{scale})")
            } else if precision == 16 {
                "SMALLDECIMAL".into()
            } else {
                "DECIMAL".into()
            }
        }
        TypeId::REAL => "REAL".into(),
        TypeId::DOUBLE => "DOUBLE".into(),
        TypeId::CHAR => sized("CHAR"),
        TypeId::VARCHAR => sized("VARCHAR"),
        TypeId::NCHAR => sized("NCHAR"),
        TypeId::NVARCHAR | TypeId::STRING | TypeId::NSTRING => sized("NVARCHAR"),
        TypeId::ALPHANUM => sized("ALPHANUM"),
        TypeId::SHORTTEXT => sized("SHORTTEXT"),
        TypeId::BINARY => sized("BINARY"),
        TypeId::VARBINARY | TypeId::BSTRING => sized("VARBINARY"),
        TypeId::CLOB => "CLOB".into(),
        TypeId::NCLOB => "NCLOB".into(),
        TypeId::TEXT => "TEXT".into(),
        TypeId::BINTEXT => "BINTEXT".into(),
        TypeId::BLOB | TypeId::BLOCATOR => "BLOB".into(),
        TypeId::BOOLEAN => "BOOLEAN".into(),
        TypeId::LONGDATE => "TIMESTAMP".into(),
        TypeId::SECONDDATE => "SECONDDATE".into(),
        TypeId::DAYDATE => "DATE".into(),
        TypeId::SECONDTIME => "TIME".into(),
        TypeId::GEOMETRY => "ST_GEOMETRY".into(),
        TypeId::POINT => "ST_POINT".into(),
    }
}

/// A fetched value as its cell; LOBs are read whole.
async fn to_cell(v: HdbValue<'static>) -> Result<Cell> {
    Ok(match v {
        HdbValue::ASYNC_CLOB(c) => Cell::Text(c.into_string().await.map_err(err)?),
        HdbValue::ASYNC_NCLOB(c) => Cell::Text(c.into_string().await.map_err(err)?),
        HdbValue::ASYNC_BLOB(b) => Cell::Bytes(b.into_bytes().await.map_err(err)?),
        HdbValue::ARRAY(_) => Cell::Json(super::cell(v).await.as_str().unwrap_or("[]").to_string()),
        other => plain_cell(other)?,
    })
}

/// Values that need no round trip.
fn plain_cell(v: HdbValue<'static>) -> Result<Cell> {
    Ok(match v {
        // Text the client could decode neither as CESU-8 nor as UTF-8:
        // any decoding here would change it.
        HdbValue::DBSTRING(b) => {
            return Err(Error::Query(format!(
                "Un texto del origen tiene bytes que no son CESU-8 ni UTF-8 válidos ({} bytes) y no se puede copiar sin alterarlo.",
                b.len()
            )))
        }
        HdbValue::NULL => Cell::Null,
        HdbValue::TINYINT(n) => Cell::Int(i64::from(n)),
        HdbValue::SMALLINT(n) => Cell::Int(i64::from(n)),
        HdbValue::INT(n) => Cell::Int(i64::from(n)),
        HdbValue::BIGINT(n) => Cell::Int(n),
        HdbValue::DECIMAL(d) => Cell::Decimal(plain_decimal(&d.to_string()).map_err(Error::Query)?),
        HdbValue::REAL(f) => Cell::Float(f64::from(f)),
        HdbValue::DOUBLE(f) => Cell::Float(f),
        HdbValue::BOOLEAN(b) => Cell::Bool(b),
        HdbValue::STRING(s) => Cell::Text(s),
        HdbValue::STR(s) => Cell::Text(s.to_string()),
        HdbValue::BINARY(b) | HdbValue::GEOMETRY(b) | HdbValue::POINT(b) => Cell::Bytes(b),
        HdbValue::LONGDATE(d) => Cell::DateTime(iso(&d.to_string())),
        HdbValue::SECONDDATE(d) => Cell::DateTime(iso(&d.to_string())),
        HdbValue::DAYDATE(d) => Cell::Date(d.to_string()),
        HdbValue::SECONDTIME(t) => Cell::Time(t.to_string()),
        other => Cell::Text(other.to_string()),
    })
}

/// Longest plain decimal text built from an exponent. HANA's widest
/// decimal (the floating DECIMAL, exponent about -6111 to +6144) fits;
/// past it the value can't be stored anyway, and building the text would
/// take memory by the exponent (`1E+100000000` is 100 MB).
const PLAIN_DECIMAL_MAX: i128 = 8_192;

/// Decimal text without exponent: `1.5E+3` → `1500`, `-12E-4` → `-0.0012`.
/// An exponent that would make the text longer than
/// [`PLAIN_DECIMAL_MAX`] is refused before anything is built (a zero
/// mantissa is just `0`).
fn plain_decimal(s: &str) -> std::result::Result<String, String> {
    let Some(e) = s.find(['e', 'E']) else {
        return Ok(s.to_string());
    };
    let (mantissa, exp) = (&s[..e], &s[e + 1..]);
    let Ok(exp) = exp.trim_start_matches('+').parse::<i128>() else {
        // Not a number, or past i128: invalid either way.
        return Err(format!("«{s}» no es un decimal válido o no entra en un DECIMAL"));
    };
    let (neg, mantissa) = match mantissa.strip_prefix('-') {
        Some(m) => (true, m),
        None => (false, mantissa.strip_prefix('+').unwrap_or(mantissa)),
    };
    let (int, frac) = mantissa.split_once('.').unwrap_or((mantissa, ""));
    let digits = format!("{int}{frac}");
    // Only ASCII digits: the text is cut by byte below.
    if digits.is_empty() || !digits.bytes().all(|b| b.is_ascii_digit()) {
        return Err(format!("«{s}» no es un decimal válido"));
    }
    // Position of the point from the start of `digits`.
    let point = int.len() as i128 + exp;
    let len = digits.len() as i128;
    let out_len = if point <= 0 { 1 - point + len } else { point.max(len) };
    if out_len > PLAIN_DECIMAL_MAX {
        if digits.bytes().all(|b| b == b'0') {
            return Ok("0".into());
        }
        return Err(format!("«{s}» no entra en un DECIMAL"));
    }
    let (int, frac) = if point <= 0 {
        ("0".to_string(), format!("{}{digits}", "0".repeat((-point) as usize)))
    } else if point as usize >= digits.len() {
        (format!("{digits}{}", "0".repeat(point as usize - digits.len())), String::new())
    } else {
        (digits[..point as usize].to_string(), digits[point as usize..].to_string())
    };
    let int = int.trim_start_matches('0');
    let int = if int.is_empty() { "0" } else { int };
    let sign = if neg { "-" } else { "" };
    Ok(if frac.is_empty() { format!("{sign}{int}") } else { format!("{sign}{int}.{frac}") })
}

// ---------------------------------------------------------------- loading

/// How a target column takes its values.
#[derive(Debug, Clone, PartialEq)]
enum Mode {
    Plain,
    /// `ST_GEOMETRY` / `ST_POINT`: WKB through one parameter, WKT through
    /// another.
    Spatial { srid: i64 },
}

/// A target column being loaded.
#[derive(Debug, Clone, PartialEq)]
struct Col {
    name: String,
    /// Its position in the batches' rows.
    index: usize,
    mode: Mode,
    /// A `GENERATED BY DEFAULT AS IDENTITY` column written with the given
    /// values (`keep_identity`): its next value moves past them at the end.
    identity: bool,
}

/// A target column in the catalog.
#[derive(Debug, Clone, Default)]
struct Target {
    data_type: String,
    /// SYS.TABLE_COLUMNS.GENERATION_TYPE (`ALWAYS AS IDENTITY`,
    /// `BY DEFAULT AS IDENTITY`, `ALWAYS AS <expr>`).
    generation: Option<String>,
    srid: Option<i64>,
    not_null: bool,
}

const LOAD_COLUMNS: &str = "SELECT COLUMN_NAME, DATA_TYPE_NAME, GENERATION_TYPE, IS_NULLABLE FROM SYS.TABLE_COLUMNS
  WHERE SCHEMA_NAME = ? AND TABLE_NAME = ?";
const LOAD_SRIDS: &str = "SELECT COLUMN_NAME, SRS_ID FROM SYS.ST_GEOMETRY_COLUMNS WHERE SCHEMA_NAME = ? AND TABLE_NAME = ?";

/// The columns the load writes, checked against the target.
fn plan(qualified: &str, targets: &HashMap<String, Target>, spec: &LoadSpec) -> Result<Vec<Col>> {
    if targets.is_empty() {
        return Err(Error::Query(format!("No existe la tabla {qualified} o no se tiene acceso.")));
    }
    let mut cols = Vec::new();
    for (index, name) in spec.columns.iter().enumerate() {
        let Some(t) = targets.get(name) else {
            return Err(Error::Query(format!("La tabla {qualified} no tiene la columna {name}.")));
        };
        let mut identity = false;
        if let Some(g) = t.generation.as_deref().map(str::to_ascii_uppercase).filter(|g| !g.is_empty()) {
            if !g.contains("IDENTITY") {
                continue; // computed: HANA fills it.
            }
            if !spec.keep_identity {
                continue; // HANA generates it.
            }
            if g.starts_with("ALWAYS") {
                return Err(Error::Unsupported(format!(
                    "La columna {name} de {qualified} es GENERATED ALWAYS AS IDENTITY y no acepta valores. \
                     Para conservarlos hay que pasarla antes a GENERATED BY DEFAULT, o copiar sin conservar la identidad."
                )));
            }
            identity = true;
        }
        let spatial = matches!(t.data_type.to_ascii_uppercase().as_str(), "ST_GEOMETRY" | "ST_POINT");
        let mode = if spatial { Mode::Spatial { srid: t.srid.unwrap_or(0) } } else { Mode::Plain };
        cols.push(Col { name: name.clone(), index, mode, identity });
    }
    if cols.is_empty() {
        return Err(Error::Query("No hay columnas para cargar.".into()));
    }
    Ok(cols)
}

fn insert_sql(table: &str, cols: &[Col]) -> String {
    let names: Vec<String> = cols.iter().map(|c| quote(&c.name)).collect();
    let values: Vec<String> = cols
        .iter()
        .map(|c| match c.mode {
            Mode::Plain => "?".to_string(),
            Mode::Spatial { srid } => format!("COALESCE(ST_GeomFromWKB(?, {srid}), ST_GeomFromText(?, {srid}))"),
        })
        .collect();
    format!("INSERT INTO {table} ({}) VALUES ({})", names.join(", "), values.join(", "))
}

/// Moves an identity's next value to `next` (past the loaded keys).
fn identity_sql(table: &str, col: &str, t: &Target, next: i128) -> String {
    let not_null = if t.not_null { " NOT NULL" } else { "" };
    format!(
        "ALTER TABLE {table} ALTER ({} {} GENERATED BY DEFAULT AS IDENTITY (START WITH {next}){not_null})",
        quote(col),
        t.data_type
    )
}

/// What the server asks for a parameter.
#[derive(Debug, Clone, Copy, PartialEq)]
struct Slot {
    t: TypeId,
    precision: i16,
    scale: i16,
}

impl From<TypeId> for Slot {
    fn from(t: TypeId) -> Slot {
        Slot { t, precision: 0, scale: 0 }
    }
}

impl From<&ParameterDescriptor> for Slot {
    fn from(d: &ParameterDescriptor) -> Slot {
        Slot { t: d.type_id(), precision: d.precision(), scale: d.scale() }
    }
}

/// A bound value, before it becomes the client's `HdbValue`.
#[derive(Debug, Clone, PartialEq)]
enum Param {
    Null,
    TinyInt(u8),
    SmallInt(i16),
    Int(i32),
    BigInt(i64),
    /// Plain decimal digits (checked against the parameter's precision and
    /// scale), parsed by the parameter's descriptor.
    Decimal(String),
    Real(f32),
    Double(f64),
    Bool(bool),
    Text(String),
    Bytes(Vec<u8>),
    /// A LOB too large for the batch: streamed (UTF-8 for CLOB / NCLOB).
    Stream(Vec<u8>),
}

impl Param {
    fn size(&self) -> usize {
        8 + match self {
            Param::Decimal(s) | Param::Text(s) => s.len(),
            Param::Bytes(b) | Param::Stream(b) => b.len(),
            _ => 0,
        }
    }

    fn into_hdb(self, d: &ParameterDescriptor) -> std::result::Result<HdbValue<'static>, String> {
        Ok(match self {
            Param::Null => HdbValue::NULL,
            Param::TinyInt(n) => HdbValue::TINYINT(n),
            Param::SmallInt(n) => HdbValue::SMALLINT(n),
            Param::Int(n) => HdbValue::INT(n),
            Param::BigInt(n) => HdbValue::BIGINT(n),
            Param::Decimal(s) => d.parse_value(&s).map_err(|e| format!("«{s}» no es un decimal válido: {e}"))?,
            Param::Real(f) => HdbValue::REAL(f),
            Param::Double(f) => HdbValue::DOUBLE(f),
            Param::Bool(b) => HdbValue::BOOLEAN(b),
            Param::Text(s) => HdbValue::STRING(s),
            Param::Bytes(b) => HdbValue::BINARY(b),
            Param::Stream(b) => HdbValue::ASYNC_LOBSTREAM(Some(Arc::new(tokio::sync::Mutex::new(std::io::Cursor::new(b))))),
        })
    }
}

/// Parameters the client can stream (its LOB writer takes only these).
fn is_lob(t: TypeId) -> bool {
    matches!(t, TypeId::BLOB | TypeId::CLOB | TypeId::NCLOB)
}

/// A cell as the parameter the server asks for.
fn param(c: &Cell, slot: impl Into<Slot>) -> std::result::Result<Param, String> {
    let slot = slot.into();
    let t = slot.t;
    if matches!(c, Cell::Null) {
        return Ok(Param::Null);
    }
    let p = match t {
        TypeId::TINYINT => {
            let n = integer(c)?;
            Param::TinyInt(u8::try_from(n).map_err(|_| format!("{n} no entra en un TINYINT (0 a 255)"))?)
        }
        TypeId::SMALLINT => {
            let n = integer(c)?;
            Param::SmallInt(i16::try_from(n).map_err(|_| format!("{n} no entra en un SMALLINT"))?)
        }
        TypeId::INT => {
            let n = integer(c)?;
            Param::Int(i32::try_from(n).map_err(|_| format!("{n} no entra en un INTEGER"))?)
        }
        TypeId::BIGINT => Param::BigInt(integer(c)?),
        TypeId::DECIMAL | TypeId::FIXED8 | TypeId::FIXED12 | TypeId::FIXED16 => {
            let d = decimal(c)?;
            check_decimal(&d, slot)?;
            Param::Decimal(d)
        }
        TypeId::REAL => Param::Real(real(float(c)?)?),
        TypeId::DOUBLE => Param::Double(float(c)?),
        TypeId::BOOLEAN => Param::Bool(boolean(c)?),
        TypeId::BINARY | TypeId::VARBINARY | TypeId::BSTRING | TypeId::BLOB | TypeId::BLOCATOR | TypeId::GEOMETRY | TypeId::POINT => {
            Param::Bytes(bytes(c)?)
        }
        TypeId::LONGDATE => Param::Text(timestamp(c, 7, "TIMESTAMP")?),
        TypeId::SECONDDATE => Param::Text(timestamp(c, 0, "SECONDDATE")?),
        TypeId::DAYDATE => Param::Text(date(c)?),
        TypeId::SECONDTIME => Param::Text(time(c)?),
        // Character types, CLOB / NCLOB, TEXT, ALPHANUM…
        _ => Param::Text(text(c)?),
    };
    Ok(match p {
        Param::Text(s) if is_lob(t) && s.len() > LOB_INLINE => Param::Stream(s.into_bytes()),
        Param::Bytes(b) if is_lob(t) && b.len() > LOB_INLINE => Param::Stream(b),
        // Only BLOB / CLOB / NCLOB can be streamed; anything else (TEXT,
        // BINTEXT…) goes whole in the request, so a huge one is refused
        // before it is sent.
        Param::Text(_) | Param::Bytes(_) if p.size() - 8 > INLINE_MAX => {
            return Err(format!(
                "un valor de {} MiB no se puede enviar a una columna {t:?}: el cliente de HANA solo manda por partes BLOB, CLOB y NCLOB, y sin eso el máximo es {} MiB",
                (p.size() - 8).div_ceil(1024 * 1024),
                INLINE_MAX / (1024 * 1024)
            ));
        }
        p => p,
    })
}

/// A row's parameters, in the statement's order (two per spatial column).
fn row_params(cols: &[Col], row: &[Cell], slots: &[Slot]) -> std::result::Result<Vec<Param>, (usize, String)> {
    let mut out = Vec::with_capacity(slots.len());
    for (ci, col) in cols.iter().enumerate() {
        let c = &row[col.index];
        match col.mode {
            Mode::Plain => out.push(param(c, slots[out.len()]).map_err(|e| (ci, e))?),
            Mode::Spatial { srid } => {
                let (wkb, wkt) = spatial(c, srid).map_err(|e| (ci, e))?;
                let wkb = match wkb {
                    Some(b) => param(&Cell::Bytes(b), slots[out.len()]).map_err(|e| (ci, e))?,
                    None => Param::Null,
                };
                out.push(wkb);
                let wkt = match wkt {
                    Some(s) => param(&Cell::Text(s), slots[out.len()]).map_err(|e| (ci, e))?,
                    None => Param::Null,
                };
                out.push(wkt);
            }
        }
    }
    Ok(out)
}

/// A spatial value as ISO WKB or as WKT, for a column with `srid`. EWKB
/// (PostGIS) becomes ISO WKB and hex-encoded WKB is decoded; a value with
/// another SRID, or GeoJSON, is refused (HANA would store it as is).
fn spatial(c: &Cell, srid: i64) -> std::result::Result<(Option<Vec<u8>>, Option<String>), String> {
    match c {
        Cell::Null => Ok((None, None)),
        Cell::Bytes(b) => Ok((Some(iso_wkb(b, srid)?), None)),
        Cell::Text(s) => {
            let s = s.trim();
            if let Some(b) = hex_wkb(s) {
                return Ok((Some(iso_wkb(&b, srid)?), None));
            }
            // EWKT: `SRID=4326;POINT (1 2)`.
            let wkt = match s.get(..5).filter(|p| p.eq_ignore_ascii_case("SRID=")).and_then(|_| s[5..].split_once(';')) {
                Some((n, rest)) => {
                    let n: i64 = n.trim().parse().map_err(|_| format!("«{s}» no es un WKT válido"))?;
                    check_srid(n, srid)?;
                    rest.trim()
                }
                None => s,
            };
            Ok((None, Some(wkt.to_string())))
        }
        Cell::Json(_) => {
            Err("un valor espacial en GeoJSON no se puede cargar en HANA sin convertirlo; hace falta WKB o WKT".into())
        }
        other => Err(format!("un valor espacial tiene que ser WKB o WKT, no {other:?}")),
    }
}

fn check_srid(value: i64, column: i64) -> std::result::Result<(), String> {
    if value != 0 && value != column {
        return Err(format!("el valor tiene SRID {value} y la columna {column}; HANA no transforma coordenadas al cargar"));
    }
    Ok(())
}

/// Hex text that looks like (E)WKB (`0101000000…`, PostGIS's text form).
fn hex_wkb(s: &str) -> Option<Vec<u8>> {
    if s.len() < 10 || !s.len().is_multiple_of(2) || !(s.starts_with("00") || s.starts_with("01")) || !s.bytes().all(|b| b.is_ascii_hexdigit()) {
        return None;
    }
    (0..s.len() / 2).map(|i| u8::from_str_radix(&s[i * 2..i * 2 + 2], 16).ok()).collect()
}

/// (E)WKB → ISO WKB: EWKB's Z / M / SRID flags become ISO type codes (the
/// SRID has to be the column's). Plain WKB comes out unchanged.
fn iso_wkb(b: &[u8], srid: i64) -> std::result::Result<Vec<u8>, String> {
    let mut out = Vec::with_capacity(b.len());
    let mut at = 0;
    let found = wkb_geometry(b, &mut at, &mut out, true)?;
    if at != b.len() {
        return Err("el WKB tiene bytes de más".into());
    }
    if let Some(found) = found {
        check_srid(found, srid)?;
    }
    Ok(out)
}

fn wkb_u32(b: &[u8], at: &mut usize, le: bool) -> std::result::Result<u32, String> {
    let raw: [u8; 4] = b.get(*at..*at + 4).and_then(|s| s.try_into().ok()).ok_or("el WKB está cortado")?;
    *at += 4;
    Ok(if le { u32::from_le_bytes(raw) } else { u32::from_be_bytes(raw) })
}

fn wkb_put(out: &mut Vec<u8>, n: u32, le: bool) {
    out.extend_from_slice(&if le { n.to_le_bytes() } else { n.to_be_bytes() });
}

fn wkb_copy(b: &[u8], at: &mut usize, out: &mut Vec<u8>, len: usize) -> std::result::Result<(), String> {
    let end = at.checked_add(len).filter(|e| *e <= b.len()).ok_or("el WKB está cortado")?;
    out.extend_from_slice(&b[*at..end]);
    *at = end;
    Ok(())
}

/// Copies one geometry; its EWKB SRID, if it has one.
fn wkb_geometry(b: &[u8], at: &mut usize, out: &mut Vec<u8>, top: bool) -> std::result::Result<Option<i64>, String> {
    let order = *b.get(*at).ok_or("el WKB está cortado")?;
    if order > 1 {
        return Err("el valor no es WKB".into());
    }
    out.push(order);
    *at += 1;
    let le = order == 1;
    let raw = wkb_u32(b, at, le)?;
    let (mut z, mut m) = (raw & 0x8000_0000 != 0, raw & 0x4000_0000 != 0);
    let code = raw & 0x0FFF_FFFF;
    match code / 1000 {
        0 => {}
        1 => z = true,
        2 => m = true,
        3 => (z, m) = (true, true),
        _ => return Err(format!("tipo de geometría WKB desconocido ({raw})")),
    }
    let base = code % 1000;
    if !(1..=7).contains(&base) {
        return Err(format!("tipo de geometría WKB desconocido ({raw})"));
    }
    let srid = if raw & 0x2000_0000 != 0 {
        if !top {
            return Err("el WKB tiene un SRID dentro de una colección".into());
        }
        Some(i64::from(wkb_u32(b, at, le)? as i32))
    } else {
        None
    };
    wkb_put(out, base + if z { 1000 } else { 0 } + if m { 2000 } else { 0 }, le);
    let point = 8 * (2 + usize::from(z) + usize::from(m));
    let points = |b: &[u8], at: &mut usize, out: &mut Vec<u8>| -> std::result::Result<(), String> {
        let n = wkb_u32(b, at, le)?;
        wkb_put(out, n, le);
        wkb_copy(b, at, out, (n as usize).checked_mul(point).ok_or("el WKB está cortado")?)
    };
    match base {
        1 => wkb_copy(b, at, out, point)?,
        2 => points(b, at, out)?,
        3 => {
            let rings = wkb_u32(b, at, le)?;
            wkb_put(out, rings, le);
            for _ in 0..rings {
                points(b, at, out)?;
            }
        }
        _ => {
            let n = wkb_u32(b, at, le)?;
            wkb_put(out, n, le);
            for _ in 0..n {
                wkb_geometry(b, at, out, false)?;
            }
        }
    }
    Ok(srid)
}

fn integer(c: &Cell) -> std::result::Result<i64, String> {
    match c {
        Cell::Int(n) => Ok(*n),
        Cell::UInt(n) => i64::try_from(*n).map_err(|_| format!("{n} no entra en un BIGINT")),
        Cell::Bool(b) => Ok(i64::from(*b)),
        Cell::Float(f) if f.fract() == 0.0 && f.abs() < 9.2e18 => Ok(*f as i64),
        Cell::Decimal(s) | Cell::Text(s) => {
            let t = s.trim();
            if let Ok(n) = t.parse::<i64>() {
                return Ok(n);
            }
            // `12.000` is an integer.
            match t.split_once('.') {
                Some((i, f)) if f.bytes().all(|b| b == b'0') => i.parse().map_err(|_| format!("«{s}» no es un entero")),
                _ => Err(format!("«{s}» no es un entero")),
            }
        }
        other => Err(format!("{other:?} no es un entero")),
    }
}

fn decimal(c: &Cell) -> std::result::Result<String, String> {
    match c {
        Cell::Int(n) => Ok(n.to_string()),
        Cell::UInt(n) => Ok(n.to_string()),
        Cell::Bool(b) => Ok(if *b { "1" } else { "0" }.into()),
        Cell::Float(f) if f.is_finite() => plain_decimal(&f.to_string()),
        Cell::Decimal(s) | Cell::Text(s) => plain_decimal(s.trim()),
        other => Err(format!("{other:?} no es un decimal")),
    }
}

/// Refuses a decimal the parameter would change: the client cuts FIXED
/// values to the column's scale (no rounding) and writes past a FIXED12's
/// bytes, and it cuts floating DECIMAL mantissas past 34 digits.
fn check_decimal(s: &str, slot: Slot) -> std::result::Result<(), String> {
    let digits = s.strip_prefix(['-', '+']).unwrap_or(s);
    let (int, frac) = digits.split_once('.').unwrap_or((digits, ""));
    if (int.is_empty() && frac.is_empty()) || !int.bytes().chain(frac.bytes()).all(|b| b.is_ascii_digit()) {
        return Err(format!("«{s}» no es un decimal válido"));
    }
    let (int, frac) = (int.trim_start_matches('0'), frac.trim_end_matches('0'));
    let cap: i16 = match slot.t {
        TypeId::FIXED8 => 18,
        TypeId::FIXED12 => 28,
        TypeId::FIXED16 => 38,
        // A DECIMAL(p,s) described as DECIMAL (servers without the FIXED
        // types): HANA rounds or cuts it to the scale, so it is checked
        // like a FIXED one. Floating DECIMAL / SMALLDECIMAL report a scale
        // outside 0..=precision.
        TypeId::DECIMAL if slot.precision > 0 && slot.precision <= 38 && (0..=slot.precision).contains(&slot.scale) => 38,
        _ => {
            // Floating DECIMAL (34 digits) or SMALLDECIMAL (16).
            let max = if (1..=34).contains(&slot.precision) { slot.precision as usize } else { 34 };
            let significant = format!("{int}{frac}");
            if significant.trim_matches('0').len() > max {
                return Err(format!("«{s}» tiene más de {max} dígitos significativos y HANA lo redondearía"));
            }
            return Ok(());
        }
    };
    let precision = if slot.precision > 0 { slot.precision.min(cap) } else { cap };
    let scale = slot.scale.clamp(0, precision);
    if frac.len() > scale as usize {
        return Err(format!("«{s}» tiene más decimales de los que admite DECIMAL({precision},{scale}); se perderían dígitos"));
    }
    if int.len() > (precision - scale) as usize {
        return Err(format!("«{s}» no entra en un DECIMAL({precision},{scale})"));
    }
    Ok(())
}

/// A REAL / DOUBLE value. HANA has no NaN nor infinity (and the client
/// sends a NaN as NULL), so those are refused rather than stored as
/// something else. An integer or decimal a DOUBLE can't hold exactly
/// (`9007199254740993`, `1.00000000000000001`) is refused too.
fn float(c: &Cell) -> std::result::Result<f64, String> {
    let lossy = |shown: &dyn std::fmt::Display, f: f64| {
        format!("{shown} no entra exacto en un DOUBLE (quedaría {f:e}); se perderían dígitos")
    };
    let f = match c {
        Cell::Float(f) => *f,
        Cell::Int(n) => {
            let f = *n as f64;
            if f as i128 != i128::from(*n) {
                return Err(lossy(n, f));
            }
            f
        }
        Cell::UInt(n) => {
            let f = *n as f64;
            if f as i128 != i128::from(*n) {
                return Err(lossy(n, f));
            }
            f
        }
        Cell::Bool(b) => f64::from(u8::from(*b)),
        Cell::Decimal(s) | Cell::Text(s) => {
            let t = s.trim();
            let f: f64 = t.parse().map_err(|_| format!("«{s}» no es un número"))?;
            if f.is_finite() && significand(t) != significand(&format!("{f:e}")) {
                return Err(lossy(&format!("«{t}»"), f));
            }
            f
        }
        other => return Err(format!("{other:?} no es un número")),
    };
    if !f.is_finite() {
        return Err(format!("{f} no se puede guardar: HANA no tiene NaN ni infinito en REAL ni DOUBLE"));
    }
    Ok(f)
}

/// A decimal number's value as (negative, significant digits, position of
/// the point before them): `-12.50e1` → `(true, "125", 3)`. Zero is
/// `(false, "", 0)`. `None` when it isn't plain decimal notation.
fn significand(s: &str) -> Option<(bool, String, i128)> {
    let (mantissa, exp) = match s.find(['e', 'E']) {
        Some(i) => (&s[..i], s[i + 1..].trim_start_matches('+').parse::<i128>().ok()?),
        None => (s, 0),
    };
    let (neg, mantissa) = match mantissa.strip_prefix('-') {
        Some(m) => (true, m),
        None => (false, mantissa.strip_prefix('+').unwrap_or(mantissa)),
    };
    let (int, frac) = mantissa.split_once('.').unwrap_or((mantissa, ""));
    if (int.is_empty() && frac.is_empty()) || !int.bytes().chain(frac.bytes()).all(|b| b.is_ascii_digit()) {
        return None;
    }
    let digits = format!("{int}{frac}");
    let lead = digits.len() - digits.trim_start_matches('0').len();
    let sig = digits.trim_matches('0');
    if sig.is_empty() {
        return Some((false, String::new(), 0));
    }
    Some((neg, sig.to_string(), int.len() as i128 - lead as i128 + exp))
}

/// A REAL, refusing what it can't hold: out of range, or more digits than
/// a REAL keeps (a value with up to 6 significant digits survives, as text).
fn real(f: f64) -> std::result::Result<f32, String> {
    if !f.is_finite() {
        return Err(format!("{f} no se puede guardar: HANA no tiene NaN ni infinito en un REAL"));
    }
    let r = f as f32;
    if f64::from(r) == f {
        return Ok(r);
    }
    if r.is_infinite() {
        return Err(format!("{f} no entra en un REAL"));
    }
    if r.abs() < f32::MIN_POSITIVE {
        return Err(format!("{f} es demasiado chico para un REAL sin perder precisión"));
    }
    // The REAL keeps the value when it reads back as the same decimal
    // number (`0.1`, `3.4028235e38`, the REAL's largest): only digits the
    // REAL can't show are lost.
    if significand(&format!("{r:e}")) != significand(&format!("{f:e}")) {
        return Err(format!("{f} tiene más precisión de la que guarda un REAL (quedaría {r:e})"));
    }
    Ok(r)
}

fn boolean(c: &Cell) -> std::result::Result<bool, String> {
    match c {
        Cell::Bool(b) => Ok(*b),
        Cell::Int(n) => Ok(*n != 0),
        Cell::UInt(n) => Ok(*n != 0),
        Cell::Decimal(s) | Cell::Text(s) => match s.trim().to_ascii_lowercase().as_str() {
            "1" | "true" | "t" | "y" | "yes" | "on" => Ok(true),
            "0" | "false" | "f" | "n" | "no" | "off" => Ok(false),
            _ => Err(format!("«{s}» no es un booleano")),
        },
        other => Err(format!("{other:?} no es un booleano")),
    }
}

fn bytes(c: &Cell) -> std::result::Result<Vec<u8>, String> {
    match c {
        Cell::Bytes(b) => Ok(b.clone()),
        Cell::Uuid(u) => uuid_bytes(u).ok_or_else(|| format!("«{u}» no es un UUID")),
        Cell::Text(s) | Cell::Json(s) => Ok(s.as_bytes().to_vec()),
        other => Err(format!("{other:?} no es binario")),
    }
}

/// `8-4-4-4-12` hex → its 16 bytes.
fn uuid_bytes(u: &str) -> Option<Vec<u8>> {
    let hex: String = u.chars().filter(|c| *c != '-').collect();
    if hex.len() != 32 {
        return None;
    }
    (0..16).map(|i| u8::from_str_radix(&hex[i * 2..i * 2 + 2], 16).ok()).collect()
}

fn text(c: &Cell) -> std::result::Result<String, String> {
    Ok(match c {
        Cell::Null => String::new(),
        Cell::Bool(b) => if *b { "TRUE" } else { "FALSE" }.into(),
        Cell::Int(n) => n.to_string(),
        Cell::UInt(n) => n.to_string(),
        Cell::Float(f) => f.to_string(),
        Cell::Bytes(b) => std::str::from_utf8(b)
            .map_err(|_| format!("{} bytes que no son UTF-8 válido no se pueden guardar como texto sin alterarlos", b.len()))?
            .to_string(),
        Cell::Decimal(s)
        | Cell::Text(s)
        | Cell::Date(s)
        | Cell::Time(s)
        | Cell::DateTime(s)
        | Cell::DateTimeTz(s)
        | Cell::Uuid(s)
        | Cell::Json(s) => s.clone(),
    })
}

/// `YYYY-MM-DD HH:MM:SS[.f]` with at most `digits` fraction digits (TIMESTAMP
/// keeps 7, SECONDDATE none; more non-zero digits are refused). With a
/// zone, in UTC (HANA has no zoned type).
fn timestamp(c: &Cell, digits: usize, what: &str) -> std::result::Result<String, String> {
    let s = match c {
        Cell::Date(d) => format!("{} 00:00:00", d.trim()),
        // Text (or a date-time) with a zone is moved to UTC like a zoned
        // cell: HANA's implicit conversion would refuse or drop the zone.
        Cell::DateTime(s) | Cell::Text(s) => match split_clock(s) {
            Some((day, clock)) if is_zoned(&clock) => {
                let joined = format!("{day} {clock}");
                to_utc(&joined).map_err(|e| format!("«{}» no es una fecha y hora con zona válida: {e}", s.trim()))?
            }
            Some((day, clock)) => format!("{day} {clock}"),
            // A time of day HANA's implicit conversion could read otherwise
            // (`10:00:00 PM`, `10:00:00 UTC`): refused, not sent as is.
            None if s.contains(':') => return Err(unclear_clock(s)),
            None => s.trim().to_string(),
        },
        Cell::DateTimeTz(s) => {
            to_utc(&comma_fraction(s.trim())).map_err(|e| format!("«{}» no es una fecha y hora con zona válida: {e}", s.trim()))?
        }
        other => return Err(format!("{other:?} no es una fecha y hora")),
    };
    fraction(&s, digits, what)
}

/// A date-time's date and time of day, split at the first space or `T`
/// followed by a digit where what follows is a whole time of day (so
/// `2024-1-1 10:30`, `20240101T1030` and `2024-01-01 10:00:00,5` all
/// split; a comma fraction becomes a point). After a space the time needs
/// its colons, so the year of `01 Oct 2024` isn't taken for a time.
/// `None` when no such time follows (`10:00:00 PM`, `10:00 UTC`).
fn split_clock(s: &str) -> Option<(String, String)> {
    let s = s.trim();
    let b = s.as_bytes();
    (1..b.len())
        .filter(|&i| matches!(b[i], b' ' | b'T' | b't') && b.get(i + 1).is_some_and(u8::is_ascii_digit))
        .map(|i| (i, s[..i].trim().to_string(), comma_fraction(s[i + 1..].trim())))
        .find(|(i, _, clock)| clock_parts(clock).is_some() && (b[*i] != b' ' || clock.contains(':')))
        .map(|(_, day, clock)| (day, clock))
}

/// A time of day's clock and zone, when its shape is one HANA can only
/// read one way: `H[H]:M[M][:S[S][.f]]` or compact `HHMM` / `HHMMSS[.f]`,
/// then optionally `Z`, `±HH`, `±HHMM` or `±HH:MM`. Anything else
/// (`10:00 PM`, `10:00 UTC`, `10:00:00 +01:00`) is `None`.
fn clock_parts(s: &str) -> Option<(&str, Option<&str>)> {
    let digits = |t: &str, min: usize, max: usize| (min..=max).contains(&t.len()) && t.bytes().all(|b| b.is_ascii_digit());
    let (clock, zone) = match s.strip_suffix(['Z', 'z']) {
        Some(c) => (c, Some(&s[c.len()..])),
        None => match s.find(['+', '-']) {
            Some(i) => {
                let z = &s[i + 1..];
                let ok = match z.split_once(':') {
                    Some((h, m)) => digits(h, 2, 2) && digits(m, 2, 2),
                    None => digits(z, 2, 2) || digits(z, 4, 4),
                };
                if !ok {
                    return None;
                }
                (&s[..i], Some(&s[i..]))
            }
            None => (s, None),
        },
    };
    let (main, frac) = match clock.split_once('.') {
        Some((m, f)) if digits(f, 1, usize::MAX) => (m, true),
        Some(_) => return None,
        None => (clock, false),
    };
    let ok = if main.contains(':') {
        let parts: Vec<&str> = main.split(':').collect();
        matches!(parts.len(), 2 | 3) && parts.iter().all(|p| digits(p, 1, 2)) && (!frac || parts.len() == 3)
    } else {
        digits(main, 6, 6) || (digits(main, 4, 4) && !frac)
    };
    ok.then_some((clock, zone))
}

fn unclear_clock(s: &str) -> String {
    format!(
        "«{}» no tiene la hora en un formato que HANA lea de una sola forma (HH:MM[:SS[.f]], con zona Z o ±HH:MM opcional); \
         con AM/PM o un nombre de zona podría guardarse otra hora",
        s.trim()
    )
}

/// `10:00:00,5` → `10:00:00.5` (a comma as the seconds' decimal separator).
fn comma_fraction(s: &str) -> String {
    match s.rfind(',') {
        Some(i) if s[..i].contains(':') && s.as_bytes().get(i + 1).is_some_and(u8::is_ascii_digit) => {
            format!("{}.{}", &s[..i], &s[i + 1..])
        }
        _ => s.to_string(),
    }
}

/// Whether a time of day carries a zone (`Z`, `+02:00`, `-0300`).
fn is_zoned(clock: &str) -> bool {
    clock.ends_with(['Z', 'z']) || clock.contains(['+', '-'])
}

/// A date; a date-time only at midnight (a DATE has no time of day).
fn date(c: &Cell) -> std::result::Result<String, String> {
    match c {
        Cell::Date(d) => Ok(d.trim().to_string()),
        // Text with a time of day goes through the same check as a
        // date-time (HANA's implicit conversion could drop the time),
        // wherever the time starts (`2024-1-1 10:30`, `20240101 10:00`).
        Cell::Text(d) => match split_clock(d) {
            Some((day, clock)) => {
                let joined = format!("{day} {clock}");
                date(&if is_zoned(&clock) { Cell::DateTimeTz(joined) } else { Cell::DateTime(joined) })
            }
            None if d.contains(':') => Err(format!("«{}» no es una fecha que se pueda leer sin ambigüedad", d.trim())),
            None => Ok(d.trim().to_string()),
        },
        Cell::DateTime(_) | Cell::DateTimeTz(_) => {
            let ts = timestamp(c, 9, "DATE")?;
            let Some((day, clock)) = split_clock(&ts) else {
                return Ok(ts);
            };
            if !clock.bytes().all(|b| matches!(b, b'0' | b':' | b'.')) {
                return Err(format!("«{ts}» tiene hora y un DATE no la guarda"));
            }
            Ok(day)
        }
        other => Err(format!("{other:?} no es una fecha")),
    }
}

/// A time of day, to the second (HANA's TIME has no fraction).
fn time(c: &Cell) -> std::result::Result<String, String> {
    match c {
        Cell::Time(t) | Cell::Text(t) => {
            let t = comma_fraction(t.trim());
            // A date or a zone would be dropped (or misread) by HANA's
            // implicit conversion: refused, like a date-time cell. So is a
            // clock HANA could read another way (`10:00:00 PM`).
            match clock_parts(&t) {
                Some((_, Some(_))) => Err(format!("«{t}» tiene zona horaria y un TIME no la guarda")),
                Some((clock, None)) => fraction(clock, 0, "TIME"),
                None => {
                    let head = t.split([' ', 'T', 't']).next().unwrap_or_default();
                    if head.contains(['-', '/']) || (t.contains([' ', 'T', 't']) && clock_parts(head).is_none()) {
                        Err(format!("«{t}» tiene fecha y un TIME no la guarda"))
                    } else {
                        Err(unclear_clock(&t))
                    }
                }
            }
        }
        other => Err(format!("{other:?} no es una hora")),
    }
}

/// The fraction of seconds kept to `digits` (no point when 0); non-zero
/// digits past them are refused, not cut.
fn fraction(s: &str, digits: usize, what: &str) -> std::result::Result<String, String> {
    match s.rsplit_once('.') {
        Some((head, frac)) if frac.bytes().all(|b| b.is_ascii_digit()) && head.contains(':') => {
            let (kept, rest) = frac.split_at(frac.len().min(digits));
            if rest.bytes().any(|b| b != b'0') {
                return Err(format!("«{s}» tiene más fracción de segundo de la que guarda un {what} ({digits} dígitos)"));
            }
            let kept = kept.trim_end_matches('0');
            Ok(if kept.is_empty() { head.to_string() } else { format!("{head}.{kept}") })
        }
        _ => Ok(s.to_string()),
    }
}

/// `YYYY-MM-DD HH:MM[:SS[.f]]±HH[:MM]` (or `Z`) → the same instant in
/// UTC, without zone. A date or time that doesn't exist (`2024-02-30`,
/// `25:61`) is refused: the day arithmetic would otherwise roll it over
/// into another, valid instant.
fn to_utc(s: &str) -> std::result::Result<String, String> {
    let bad = |what: &str| what.to_string();
    // Plain digits only (`parse` would take a sign).
    let num = |t: &str| -> Option<i64> {
        if t.is_empty() || t.len() > 9 || !t.bytes().all(|b| b.is_ascii_digit()) {
            return None;
        }
        t.parse().ok()
    };
    let s = s.trim().replacen('T', " ", 1);
    let (local, offset_min) = if let Some(l) = s.strip_suffix(['Z', 'z']) {
        (l.to_string(), 0i64)
    } else {
        let at = s.rfind(['+', '-']).filter(|i| *i > 10).ok_or_else(|| bad("no tiene zona"))?;
        let (l, off) = s.split_at(at);
        let sign = if off.starts_with('-') { -1 } else { 1 };
        let off = &off[1..];
        let (h, m) = match off.split_once(':') {
            Some(hm) => hm,
            None if off.len() == 2 => (off, "00"),
            None if off.len() == 4 => off.split_at(2),
            None => return Err(bad("la zona no es ±HH:MM")),
        };
        let (h, m) = (num(h).ok_or_else(|| bad("la zona no es ±HH:MM"))?, num(m).ok_or_else(|| bad("la zona no es ±HH:MM"))?);
        if h > 23 || m > 59 {
            return Err(bad("la zona no existe"));
        }
        (l.trim().to_string(), sign * (h * 60 + m))
    };
    let (date, clock) = local.split_once(' ').ok_or_else(|| bad("no tiene hora"))?;
    let (clock, frac) = match clock.split_once('.') {
        Some((c, f)) if !f.is_empty() && f.bytes().all(|b| b.is_ascii_digit()) => (c, Some(f)),
        Some(_) => return Err(bad("la fracción de segundo no es válida")),
        None => (clock, None),
    };
    let parts: Vec<Option<i64>> = date.split('-').map(num).collect();
    let [Some(y), Some(mo), Some(da)] = parts[..] else {
        return Err(bad("la fecha no es AAAA-MM-DD"));
    };
    let parts: Vec<Option<i64>> = clock.split(':').map(num).collect();
    let (h, mi, se) = match parts[..] {
        [Some(h), Some(mi)] => (h, mi, 0),
        [Some(h), Some(mi), Some(se)] => (h, mi, se),
        _ => return Err(bad("la hora no es HH:MM[:SS]")),
    };
    if !(1..=9999).contains(&y) || !(1..=12).contains(&mo) || !(1..=days_in_month(y, mo)).contains(&da) {
        return Err(format!("la fecha {y:04}-{mo:02}-{da:02} no existe"));
    }
    if h > 23 || mi > 59 || se > 59 {
        return Err(format!("la hora {h:02}:{mi:02}:{se:02} no existe"));
    }
    let local_days = days_from_civil(y, mo, da);
    let secs = local_days * 86_400 + h * 3600 + mi * 60 + se - offset_min * 60;
    let (days, rem) = (secs.div_euclid(86_400), secs.rem_euclid(86_400));
    // Before the Gregorian reform calendars disagree on which days exist
    // (1500-02-29 is Julian only): moving across a day there could land
    // on another date than HANA's, so it is refused.
    let reform = days_from_civil(1582, 10, 15);
    if days != local_days && (days < reform || local_days < reform) {
        return Err("pasarla a UTC cambia el día, y antes de 1582-10-15 los calendarios no coinciden".into());
    }
    let (y, mo, da) = civil_from_days(days);
    if !(1..=9999).contains(&y) {
        return Err("en UTC queda fuera de los años 0001 a 9999".into());
    }
    let mut out = format!("{y:04}-{mo:02}-{da:02} {:02}:{:02}:{:02}", rem / 3600, rem % 3600 / 60, rem % 60);
    if let Some(f) = frac {
        out.push('.');
        out.push_str(f);
    }
    Ok(out)
}

fn days_in_month(y: i64, m: i64) -> i64 {
    match m {
        2 if y % 4 == 0 && (y % 100 != 0 || y % 400 == 0) => 29,
        2 => 28,
        4 | 6 | 9 | 11 => 30,
        _ => 31,
    }
}

fn days_from_civil(y: i64, m: i64, d: i64) -> i64 {
    let y = if m <= 2 { y - 1 } else { y };
    let era = y.div_euclid(400);
    let yoe = y - era * 400;
    let doy = (153 * (m + if m > 2 { -3 } else { 9 }) + 2) / 5 + d - 1;
    let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    era * 146_097 + doe - 719_468
}

fn civil_from_days(z: i64) -> (i64, i64, i64) {
    let z = z + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = doy - (153 * mp + 2) / 5 + 1;
    let m = if mp < 10 { mp + 3 } else { mp - 9 };
    (yoe + era * 400 + i64::from(m <= 2), m, d)
}

pub(crate) async fn bulk_load(s: &mut HanaSession, spec: &LoadSpec, source: &mut dyn BatchSource, progress: Progress<'_>) -> Result<u64> {
    if spec.columns.is_empty() {
        return Err(Error::Query("La carga no tiene columnas.".into()));
    }
    // The load commits by windows and rolls back on error: on a session
    // with its own transaction open, that would commit or discard work
    // that isn't the load's.
    if !s.conn.is_auto_commit().await {
        return Err(Error::State(
            "La sesión tiene el auto-commit apagado y puede tener una transacción abierta. La carga masiva confirma por tandas \
             y confirmaría (o desharía) también lo pendiente: confirmá o deshacé la transacción y volvé a activar el auto-commit."
                .into(),
        ));
    }
    let owner = s.owner(&spec.table);
    let name = spec.table.name.clone();
    let table = format!("{}.{}", quote(&owner), quote(&name));
    let qualified = format!("{owner}.{name}");

    let mut targets: HashMap<String, Target> = HashMap::new();
    for r in s.rows(LOAD_COLUMNS, &[&owner, &name]).await? {
        let t = |i: usize| r.get(i).and_then(super::text);
        if let Some(col) = t(0) {
            let not_null = t(3).is_some_and(|n| n.eq_ignore_ascii_case("FALSE"));
            targets.insert(col, Target { data_type: t(1).unwrap_or_default(), generation: t(2), srid: None, not_null });
        }
    }
    if targets.values().any(|t| t.data_type.to_ascii_uppercase().starts_with("ST_")) {
        // Without the view (older versions) the SRID is 0.
        if let Ok(rows) = s.rows(LOAD_SRIDS, &[&owner, &name]).await {
            for r in rows {
                if let (Some(col), Some(srid)) = (r.first().and_then(super::text), r.get(1).and_then(super::int)) {
                    if let Some(t) = targets.get_mut(&col) {
                        t.srid = Some(srid);
                    }
                }
            }
        }
    }
    let cols = plan(&qualified, &targets, spec)?;
    let sql = insert_sql(&table, &cols);

    s.conn.set_auto_commit(false).await;
    let r = load(s, spec, (&owner, &name), &table, &cols, &targets, &sql, source, progress).await;
    if r.is_err() {
        if let Err(e) = s.conn.rollback().await {
            tracing::debug!("hana: rollback after a failed load: {}", super::message(&e));
        }
    }
    s.conn.set_auto_commit(true).await;
    r
}

#[allow(clippy::too_many_arguments)]
async fn load(
    s: &HanaSession,
    spec: &LoadSpec,
    at: (&str, &str),
    table: &str,
    cols: &[Col],
    targets: &HashMap<String, Target>,
    sql: &str,
    source: &mut dyn BatchSource,
    progress: Progress<'_>,
) -> Result<u64> {
    let mut stmt = s.conn.prepare(sql).await.map_err(err)?;
    let descriptors = stmt.parameter_descriptors();
    let descs: Vec<&ParameterDescriptor> = descriptors.iter_in().collect();
    let slots: Vec<Slot> = descs.iter().map(|d| Slot::from(*d)).collect();
    let (commit_rows, commit_bytes) = (spec.commit_rows.max(1), spec.commit_bytes.max(1));

    let mut total = 0u64;
    let (mut window_rows, mut window_bytes) = (0u64, 0u64);
    let mut batch_bytes = 0usize;
    while let Some(batch) = source.next().await {
        for row in batch.rows {
            let at = total + window_rows + 1;
            if row.len() != spec.columns.len() {
                return Err(Error::Query(format!(
                    "La fila {at} trae {} valores y la carga tiene {} columnas.",
                    row.len(),
                    spec.columns.len()
                )));
            }
            if window_rows == 0 && spec.table_lock {
                s.conn.exec(format!("LOCK TABLE {table} IN EXCLUSIVE MODE")).await.map_err(err)?;
            }
            let params = row_params(cols, &row, &slots)
                .map_err(|(ci, e)| Error::Query(format!("Fila {at}, columna «{}»: {e}", cols[ci].name)))?;
            let size: usize = params.iter().map(Param::size).sum();
            let stream = params.iter().any(|p| matches!(p, Param::Stream(_)));
            let mut values = Vec::with_capacity(params.len());
            for (p, d) in params.into_iter().zip(&descs) {
                values.push(p.into_hdb(d).map_err(|e| Error::Query(format!("Fila {at}: {e}")))?);
            }
            if stream {
                // Streamed LOBs can't go in a batch: the row goes alone.
                if stmt.current_batch_size() > 0 {
                    stmt.execute_batch().await.map_err(err)?;
                    batch_bytes = 0;
                }
                stmt.execute_row(values).await.map_err(err)?;
            } else {
                stmt.add_row_to_batch(values).map_err(err)?;
                batch_bytes += size;
                if stmt.current_batch_size() >= BATCH_ROWS || batch_bytes >= BATCH_BYTES {
                    stmt.execute_batch().await.map_err(err)?;
                    batch_bytes = 0;
                }
            }
            window_rows += 1;
            window_bytes += size as u64;
            if window_rows >= commit_rows || window_bytes >= commit_bytes {
                if stmt.current_batch_size() > 0 {
                    stmt.execute_batch().await.map_err(err)?;
                    batch_bytes = 0;
                }
                s.conn.commit().await.map_err(err)?;
                total += window_rows;
                (window_rows, window_bytes) = (0, 0);
                progress(total);
            }
        }
    }
    if stmt.current_batch_size() > 0 {
        stmt.execute_batch().await.map_err(err)?;
    }
    s.conn.commit().await.map_err(err)?;
    if window_rows > 0 {
        total += window_rows;
        progress(total);
    }
    // Identities written with the given keys go on past them. This is
    // DDL, which HANA commits on its own (DDL auto-commit is on by
    // default), so it runs after the last window is committed and
    // reported: a failure here leaves no rows committed that progress
    // didn't count, and the load still fails (the table is redone).
    for c in cols.iter().filter(|c| c.identity) {
        if let Some(t) = targets.get(&c.name) {
            move_identity(s, at, table, &c.name, t).await?;
        }
    }
    Ok(total)
}

/// A column's definition in the catalog, as far as redeclaring it for
/// [`identity_sql`] could change it.
const IDENTITY_COLUMN: &str = "SELECT DATA_TYPE_NAME, LENGTH, SCALE, IS_NULLABLE, GENERATION_TYPE, DEFAULT_VALUE, COMMENTS
  FROM SYS.TABLE_COLUMNS WHERE SCHEMA_NAME = ? AND TABLE_NAME = ? AND COLUMN_NAME = ?";

async fn column_definition(s: &HanaSession, (owner, name): (&str, &str), col: &str) -> Result<Vec<Option<String>>> {
    let rows = s.rows(IDENTITY_COLUMN, &[owner, name, col]).await?;
    Ok(rows.into_iter().next().map(|r| r.iter().map(super::text).collect()).unwrap_or_default())
}

/// `COMMENT ON COLUMN` restoring a column's comment.
fn comment_sql(table: &str, col: &str, comment: &str) -> String {
    format!("COMMENT ON COLUMN {table}.{} IS '{}'", quote(col), comment.replace('\'', "''"))
}

/// What redeclaring the identity changed besides its next value, if
/// anything (the comment is put back apart). Columns as [`IDENTITY_COLUMN`].
fn identity_changes(before: &[Option<String>], after: &[Option<String>]) -> Vec<&'static str> {
    const NAMES: [&str; 6] = ["el tipo", "el largo", "la escala", "la nulabilidad", "la generación", "el valor por defecto"];
    NAMES.iter().enumerate().filter(|(i, _)| before.get(*i) != after.get(*i)).map(|(_, n)| *n).collect()
}

/// Moves a `GENERATED BY DEFAULT AS IDENTITY` column's next value past
/// the table's largest key, so the next insert doesn't collide. HANA does
/// it by redeclaring the column: its definition is compared before and
/// after, the comment is put back if it was lost, and any other change is
/// reported as an error rather than left silently.
async fn move_identity(s: &HanaSession, at: (&str, &str), table: &str, col: &str, t: &Target) -> Result<()> {
    let Some(max) = super::single_text(&s.conn, &format!("SELECT MAX({}) FROM {table}", quote(col))).await? else {
        return Ok(()); // Empty: the identity starts where it was.
    };
    let next = max
        .trim()
        .parse::<i128>()
        .map_err(|_| Error::Query(format!("La identidad {col} tiene un máximo que no es entero ({max}).")))?
        + 1;
    let before = column_definition(s, at, col).await?;
    s.conn.exec(identity_sql(table, col, t, next)).await.map_err(|e| {
        Error::Query(format!(
            "No se pudo mover el próximo valor de la identidad {col} después de los valores copiados (hasta {max}): {}",
            super::message(&e)
        ))
    })?;
    let after = column_definition(s, at, col).await?;
    let changed = identity_changes(&before, &after);
    if !changed.is_empty() {
        return Err(Error::Query(format!(
            "Al mover el próximo valor de la identidad {col} HANA cambió {} de la columna; los datos están copiados, pero hay que revisar su definición.",
            changed.join(", ")
        )));
    }
    if let Some(Some(comment)) = before.get(6).filter(|c| c.is_some() && after.get(6) != before.get(6)) {
        s.conn.exec(comment_sql(table, col, comment)).await.map_err(|e| {
            Error::Query(format!(
                "Al mover la identidad {col} se perdió el comentario de la columna y no se pudo volver a poner: {}",
                super::message(&e)
            ))
        })?;
    }
    Ok(())
}

