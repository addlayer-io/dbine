    #[test]
    fn a_closed_gate_waits_for_the_commit_in_progress() {
        let gate = Arc::new(Gate::default());
        let held = gate.0.lock().unwrap();
        let g = gate.clone();
        let closer = std::thread::spawn(move || drop(CloseOnDrop(g)));
        std::thread::sleep(std::time::Duration::from_millis(50));
        // The "commit" still holds the lock: the drop hasn't returned.
        assert!(!closer.is_finished());
        drop(held);
        closer.join().unwrap();
        assert!(gate.closed());
    }

