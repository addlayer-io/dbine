//! Bulk transfer (see `dbine_driver::transfer`).
//!
//! - Reading: one `SELECT` fetched [`FETCH_ROWS`] rows per round trip (the
//!   first execute keeps the client's small prefetch: a large one breaks the
//!   client's decoding of `JSON` columns), each
//!   value turned into its typed cell: `NUMBER` with scale 0 → integer (or
//!   exact decimal when it doesn't fit 64 bits), other `NUMBER`s → exact
//!   decimal, `BINARY_*` → float, character types and CLOBs → text (whole),
//!   `RAW` / BLOB → bytes (whole; an empty LOB, which the client gives as
//!   NULL, is told apart by a flag in the query), `DATE` / `TIMESTAMP` →
//!   date-time,
//!   `WITH TIME ZONE` → date-time with its offset, `WITH LOCAL TIME ZONE` →
//!   read in UTC (`SYS_EXTRACT_UTC`), intervals → Oracle's own text,
//!   `JSON` → JSON text serialized by the server (`JSON_SERIALIZE`: numbers
//!   exact, members in order). Dates before year 1
//!   are text with a ` BC` suffix (`0044-03-15 12:00:00 BC`), as PostgreSQL
//!   spells them: the cells' formats have no era. Only a `SELECT` runs on
//!   the source.
//! - Loading: array DML. One `INSERT … VALUES (:1, …)` bound with up to
//!   [`ARRAY_ROWS`] rows or [`ARRAY_BYTES`] per execute (one round trip),
//!   bound with the target
//!   column's type (read from the catalog; numbers go as text through
//!   `TO_NUMBER`, with `NLS_NUMERIC_CHARACTERS` set to `.,` for the load and
//!   restored after it, because the client's own number encoding stores
//!   integers ending in `00` as invalid numbers that read back as NULL),
//!   committed every
//!   `commit_rows` / `commit_bytes`. With `table_lock` the insert is
//!   direct-path (`/*+ APPEND_VALUES */`, Oracle's hint for array inserts):
//!   Oracle then requires a commit before the table is touched again in the
//!   same transaction (ORA-12838), so each execute commits (bigger arrays).
//!   Tables with LOB or `JSON` columns load on the conventional path even
//!   with `table_lock`: direct-path array inserts into them fail with
//!   ORA-65501 depending on the order of the rows' sizes.
//!   Values over [`LOB_INLINE`] bytes can't go in a bind (the protocol's
//!   limit), so those rows go one by one through a PL/SQL block that
//!   builds a temporary LOB in 32 KB pieces (also empty CLOBs and BLOBs,
//!   which Oracle keeps apart from NULL only as LOBs).
//! - Oracle stores an empty `VARCHAR2` / `CHAR` / `RAW` as NULL: an empty
//!   text or binary for such a column stops the load (`Unsupported`)
//!   instead of turning into NULL.
//! - Text into `RAW` / BLOB: hex digits (with or without `0x`) when the
//!   source column is binary (or an ObjectId / UUID), its UTF-8 bytes when
//!   it's text; without the source's type, only `0x…` is taken as hex.
//! - Memory: the load pulls the next batch only after the worker has
//!   turned the previous one into bound values, so besides the
//!   orchestrator's window it holds at most [`ARRAY_BYTES`] of pending
//!   rows (and the client's encoding of them while they execute).
//! - A load whose future is dropped (a cancel, or a failed read) stops its
//!   worker: nothing is committed after the drop returns, and what wasn't
//!   committed is rolled back.
//! - Identity columns: `GENERATED BY DEFAULT` accept the given values;
//!   `GENERATED ALWAYS` don't, and the table is never altered here: with
//!   `keep_identity` the load stops and says so (whoever runs the migration
//!   decides whether to `ALTER TABLE … MODIFY … GENERATED BY DEFAULT`).
//!   Without `keep_identity`, identity columns are left out and Oracle
//!   generates them.
//! - Native copy (Oracle to Oracle): the same read and load, except that
//!   `WITH TIME ZONE` values travel with their region (`TZR TZD`, not just
//!   the offset) and `JSON` as Oracle's extended JSON, so extended scalars
//!   (timestamps, binaries, doubles…) keep their types.

use super::{err, join_err, panic_text, poisoned, quote, OracleSession};
use dbine_driver::transfer::{BatchBuilder, BatchSink, BatchSinkRef, BatchSource, Cell, CopySpec, LoadSpec, Progress, ReadSpec, RowBatch, TransferColumn};
use dbine_driver::{Error, Result, Session};
use oracledb::{Connection, DbType, Metadata, OracleNumber, OracleTimestamp, Row, ToDbValue};
use std::sync::atomic::Ordering;
use std::sync::{Arc, Mutex};

/// Rows per fetch round trip.
const FETCH_ROWS: u32 = 1_000;
/// Rows per array execute (conventional path)…
const ARRAY_ROWS: usize = 10_000;
/// …and with `APPEND_VALUES` (each execute commits: bigger arrays).
const DIRECT_ARRAY_ROWS: usize = 50_000;
/// Bytes of bound values per array execute: what the load holds besides
/// the orchestrator's window.
const ARRAY_BYTES: usize = 4 * 1024 * 1024;
/// Largest value that goes in a bind; larger ones go through a temporary LOB.
const LOB_INLINE: usize = 32_767;
/// Bytes per piece written into a temporary LOB (fits a PL/SQL bind).
const LOB_CHUNK: usize = 32_000;
/// Batches queued between the reader and the writer of a native copy.
const NATIVE_BATCHES: usize = 8;
/// A NUMBER's range, below 1e126 and down to 1e-130, as the power of ten
/// of `0.d…` (1e125 is 0.1e126, 1e-130 is 0.1e-129).
const NUMBER_MAX_MAGNITUDE: i64 = 126;
const NUMBER_MIN_MAGNITUDE: i64 = -129;

