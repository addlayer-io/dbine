/// How a value is bound, by the target column's type.
#[derive(Debug, Clone, Copy, PartialEq)]
enum Kind {
    /// Text through `TO_NUMBER` (see the module's docs).
    Number,
    Double,
    Text,
    Raw,
    Timestamp,
    /// Text through `TO_TIMESTAMP_TZ` (keeps the offset or the region; also
    /// for `WITH LOCAL TIME ZONE`).
    TimestampTz,
    IntervalDs,
    IntervalYm,
    Bool,
    /// Textual JSON (the server parses it into a `JSON` column).
    Json,
}

fn kind_of(data_type: &str) -> Kind {
    let t = data_type.to_ascii_uppercase();
    match t.as_str() {
        "NUMBER" | "FLOAT" | "INTEGER" => Kind::Number,
        "BINARY_FLOAT" | "BINARY_DOUBLE" => Kind::Double,
        "RAW" | "LONG RAW" | "BLOB" => Kind::Raw,
        "DATE" => Kind::Timestamp,
        "BOOLEAN" => Kind::Bool,
        "JSON" => Kind::Json,
        _ if t.starts_with("TIMESTAMP") && t.contains("TIME ZONE") => Kind::TimestampTz,
        _ if t.starts_with("TIMESTAMP") => Kind::Timestamp,
        _ if t.starts_with("INTERVAL DAY") => Kind::IntervalDs,
        _ if t.starts_with("INTERVAL YEAR") => Kind::IntervalYm,
        // VARCHAR2, NVARCHAR2, CHAR, NCHAR, CLOB, NCLOB, LONG, XMLTYPE,
        // VECTOR, ROWID…: text the server converts.
        _ => Kind::Text,
    }
}

/// `TO_TIMESTAMP_TZ`'s format: `TZR` takes an offset or a region, `TZD`
/// (optional) the daylight-saving abbreviation that settles an ambiguous
/// hour.
const TZ_FORMAT: &str = "SYYYY-MM-DD HH24:MI:SS.FF9 TZR TZD";

impl Kind {
    /// The bind's type (also the type of its NULLs: every row of an array
    /// execute binds a column with the same type).
    fn db_type(self) -> &'static DbType {
        match self {
            Kind::Double => oracledb::DB_TYPE_BINARY_DOUBLE,
            Kind::Raw => oracledb::DB_TYPE_RAW,
            Kind::Timestamp => oracledb::DB_TYPE_TIMESTAMP,
            Kind::Bool => oracledb::DB_TYPE_BOOLEAN,
            Kind::Number | Kind::Text | Kind::TimestampTz | Kind::IntervalDs | Kind::IntervalYm | Kind::Json => oracledb::DB_TYPE_VARCHAR,
        }
    }

    /// The VALUES item around the bind (`native`: JSON comes as Oracle's
    /// extended JSON).
    fn expr(self, bind: &str, native: bool) -> String {
        match self {
            Kind::Number => format!("TO_NUMBER({bind})"),
            Kind::TimestampTz => format!("TO_TIMESTAMP_TZ({bind}, '{TZ_FORMAT}')"),
            Kind::IntervalDs => format!("TO_DSINTERVAL({bind})"),
            Kind::IntervalYm => format!("TO_YMINTERVAL({bind})"),
            Kind::Json if native => format!("JSON({bind} EXTENDED)"),
            _ => bind.to_string(),
        }
    }
}

/// A bound value.
enum B {
    Null(&'static DbType),
    F(f64),
    S(String),
    R(Vec<u8>),
    T(OracleTimestamp),
    Bool(bool),
}

impl B {
    fn as_dyn(&self) -> &dyn ToDbValue {
        match self {
            B::Null(t) => t,
            B::F(f) => f,
            B::S(s) => s,
            B::R(r) => r,
            B::T(t) => t,
            B::Bool(b) => b,
        }
    }

    fn size(&self) -> usize {
        16 + match self {
            B::S(s) => s.len(),
            B::R(r) => r.len(),
            _ => 0,
        }
    }

    /// Goes through a temporary LOB: too large for a bind, or an empty LOB
    /// (an empty bind would be NULL).
    fn is_big(&self, lob: bool) -> bool {
        match self {
            B::S(s) => s.len() > LOB_INLINE || lob && s.is_empty(),
            B::R(r) => r.len() > LOB_INLINE || lob && r.is_empty(),
            _ => false,
        }
    }
}

/// How text becomes bytes for a `RAW` / BLOB column, by the source
/// column's type.
#[derive(Debug, Clone, Copy, PartialEq)]
enum RawText {
    /// Binary, ObjectId, UUID…: hex digits (`0x` optional).
    Hex,
    /// Text: its UTF-8 bytes.
    Utf8,
    /// Unknown: `0x…` hex, anything else its UTF-8 bytes.
    Unknown,
}

fn raw_text(source_type: &str) -> RawText {
    let t = source_type.to_ascii_lowercase();
    if t.trim().is_empty() {
        return RawText::Unknown;
    }
    const BINARY: [&str; 9] = ["binary", "blob", "bytea", "raw", "bytes", "image", "objectid", "bindata", "uuid"];
    if BINARY.iter().any(|b| t.contains(b)) {
        RawText::Hex
    } else {
        RawText::Utf8
    }
}

/// A target column being loaded.
#[derive(Debug, Clone)]
struct Col {
    name: String,
    kind: Kind,
    /// Its position in the batches' rows.
    index: usize,
    /// CLOB, NCLOB or BLOB.
    lob: bool,
    raw_text: RawText,
}

#[derive(Debug, Clone)]
struct Plan {
    table: String,
    /// The session's `NLS_NUMERIC_CHARACTERS` before the load.
    nls: Option<String>,
    cols: Vec<Col>,
    direct: bool,
    /// A native copy (see the module's docs).
    native: bool,
    commit_rows: u64,
    commit_bytes: u64,
}

impl Plan {
    fn insert_sql(&self) -> String {
        let names: Vec<String> = self.cols.iter().map(|c| quote(&c.name)).collect();
        let values: Vec<String> = self.cols.iter().enumerate().map(|(i, c)| c.kind.expr(&format!(":{}", i + 1), self.native)).collect();
        let hint = if self.direct { "/*+ APPEND_VALUES */ " } else { "" };
        format!("INSERT {hint}INTO {} ({}) VALUES ({})", self.table, names.join(", "), values.join(", "))
    }

    fn array_rows(&self) -> usize {
        let cap = if self.direct { DIRECT_ARRAY_ROWS } else { ARRAY_ROWS };
        cap.min(self.commit_rows.max(1) as usize)
    }
}

/// The target's columns and identities, checked against the load.
/// `source_types`: the source columns' types, in the batches' order
/// (empty when unknown).
fn plan(c: &Connection, owner: &str, table: &str, spec: &LoadSpec, source_types: &[String], native: bool) -> Result<Plan> {
    let (o, t) = (owner.to_string(), table.to_string());
    let mut types = std::collections::HashMap::new();
    for row in c
        .query("SELECT column_name, data_type FROM all_tab_columns WHERE owner = :1 AND table_name = :2", &[&o, &t])
        .map_err(err)?
    {
        let row = row.map_err(err)?;
        let (name, ty): (String, Option<String>) = (row.get(0).map_err(err)?, row.get(1).map_err(err)?);
        types.insert(name, ty.unwrap_or_default());
    }
    if types.is_empty() {
        return Err(Error::Query(format!("No existe la tabla {owner}.{table} o no se tiene acceso.")));
    }
    let mut identity = std::collections::HashMap::new();
    for row in c
        .query("SELECT column_name, generation_type FROM all_tab_identity_cols WHERE owner = :1 AND table_name = :2", &[&o, &t])
        .map_err(err)?
    {
        let row = row.map_err(err)?;
        let (name, gen): (String, Option<String>) = (row.get(0).map_err(err)?, row.get(1).map_err(err)?);
        identity.insert(name, gen.unwrap_or_default());
    }
    let mut cols = Vec::new();
    let mut lobs = false;
    for (index, name) in spec.columns.iter().enumerate() {
        let Some(ty) = types.get(name) else {
            return Err(Error::Query(format!("La tabla {owner}.{table} no tiene la columna {name}.")));
        };
        if let Some(gen) = identity.get(name) {
            if !spec.keep_identity {
                continue; // Oracle generates it.
            }
            if gen.eq_ignore_ascii_case("ALWAYS") {
                return Err(Error::Unsupported(format!(
                    "La columna {name} de {owner}.{table} es GENERATED ALWAYS AS IDENTITY y no acepta valores. \
                     Para conservarlos hay que pasarla antes a GENERATED BY DEFAULT \
                     (ALTER TABLE … MODIFY ({name} GENERATED BY DEFAULT AS IDENTITY)), o copiar sin conservar la identidad."
                )));
            }
        }
        let upper = ty.to_ascii_uppercase();
        lobs |= matches!(upper.as_str(), "CLOB" | "NCLOB" | "BLOB" | "JSON" | "XMLTYPE" | "LONG" | "LONG RAW");
        cols.push(Col {
            name: name.clone(),
            kind: kind_of(ty),
            index,
            lob: matches!(upper.as_str(), "CLOB" | "NCLOB" | "BLOB"),
            raw_text: source_types.get(index).map_or(RawText::Unknown, |t| raw_text(t)),
        });
    }
    if cols.is_empty() {
        return Err(Error::Query("No hay columnas para cargar.".into()));
    }
    let nls: Option<String> = c
        .query_row("SELECT value FROM nls_session_parameters WHERE parameter = 'NLS_NUMERIC_CHARACTERS'", &[])
        .and_then(|r| r.get(0))
        .map_err(err)?;
    if nls.as_deref() != Some(".,") {
        c.execute("ALTER SESSION SET NLS_NUMERIC_CHARACTERS = '.,'", &[]).map_err(err)?;
    }
    Ok(Plan {
        table: format!("{}.{}", quote(owner), quote(table)),
        nls: nls.filter(|v| v != ".,"),
        cols,
        direct: spec.table_lock && !lobs,
        native,
        commit_rows: spec.commit_rows.max(1),
        commit_bytes: spec.commit_bytes.max(1),
    })
}

/// Whether the load's future is still alive. The worker commits only
/// while holding the lock and seeing it open, and the future's drop takes
/// the lock to close it: once the drop returns, nothing more commits.
#[derive(Default)]
struct Gate(Mutex<bool>);

impl Gate {
    fn closed(&self) -> bool {
        self.0.lock().map_or(true, |g| *g)
    }
}

/// Closes the gate when the load's future ends, however it ends.
struct CloseOnDrop(Arc<Gate>);

impl Drop for CloseOnDrop {
    fn drop(&mut self) {
        // Waits for a commit in progress (one round trip) to finish.
        let mut g = self.0 .0.lock().unwrap_or_else(|p| p.into_inner());
        *g = true;
    }
}

pub(crate) async fn bulk_load(
    s: &mut OracleSession,
    spec: &LoadSpec,
    columns: &[TransferColumn],
    source: &mut dyn BatchSource,
    progress: Progress<'_>,
) -> Result<u64> {
    load_with(s, spec, columns, source, progress, false).await
}

async fn load_with(
    s: &mut OracleSession,
    spec: &LoadSpec,
    columns: &[TransferColumn],
    source: &mut dyn BatchSource,
    progress: Progress<'_>,
    native: bool,
) -> Result<u64> {
    let (owner, table, spec2) = (s.owner(&spec.table), spec.table.name.clone(), spec.clone());
    let source_types: Vec<String> = columns.iter().map(|c| c.type_name.clone()).collect();
    // Through `run`: reconnects first if the interrupter killed the session.
    let plan = s.run(move |c| plan(c, &owner, &table, &spec2, &source_types, native)).await?;

    let gate = Arc::new(Gate::default());
    let _close = CloseOnDrop(gate.clone());
    // `None` marks the end; a channel closed without it is a cancel. One
    // batch at a time, and the next one is pulled only when the worker has
    // taken the previous one into its bound values (`taken`): until then
    // the batch keeps its room in the orchestrator's window.
    let (tx, mut rx) = tokio::sync::mpsc::channel::<Option<Vec<Vec<Cell>>>>(1);
    let (taken_tx, mut taken) = tokio::sync::mpsc::unbounded_channel::<()>();
    let (ptx, prx) = std::sync::mpsc::channel::<u64>();
    let shared = s.shared.clone();
    let worker_gate = gate.clone();
    let worker = tokio::task::spawn_blocking(move || {
        let conn = shared.conn.lock().map_err(|_| poisoned())?;
        let mut first = true;
        let next = || {
            if !std::mem::take(&mut first) {
                let _ = taken_tx.send(());
            }
            if worker_gate.closed() {
                return Err(Error::Cancelled);
            }
            match rx.blocking_recv() {
                Some(Some(rows)) if !worker_gate.closed() => Ok(Some(rows)),
                Some(None) => Ok(None),
                _ => Err(Error::Cancelled),
            }
        };
        // A panic here must not leave the connection's lock poisoned nor
        // the transaction open.
        let r = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| load(&conn, &plan, next, &ptx, &worker_gate)))
            .unwrap_or_else(|p| Err(Error::State(format!("la carga en Oracle falló inesperadamente: {}", panic_text(&*p)))));
        if r.is_err() {
            let _ = conn.rollback();
        }
        if let Some(v) = &plan.nls {
            let _ = conn.execute(&format!("ALTER SESSION SET NLS_NUMERIC_CHARACTERS = '{}'", v.replace('\'', "''")), &[]);
        }
        r
    });
    while let Some(batch) = source.next().await {
        if tx.send(Some(batch.rows)).await.is_err() || taken.recv().await.is_none() {
            break; // The worker stopped: its error comes below.
        }
        while let Ok(n) = prx.try_recv() {
            progress(n);
        }
    }
    let _ = tx.send(None).await;
    drop(tx);
    let r = worker.await.map_err(join_err)?;
    while let Ok(n) = prx.try_recv() {
        progress(n);
    }
    if r.is_err() && s.shared.killed.load(Ordering::SeqCst) {
        return Err(Error::Cancelled);
    }
    r
}

/// Load what `next` gives until it ends; committed totals go to `committed`.
fn load(
    c: &Connection,
    plan: &Plan,
    mut next: impl FnMut() -> Result<Option<Vec<Vec<Cell>>>>,
    committed: &std::sync::mpsc::Sender<u64>,
    gate: &Gate,
) -> Result<u64> {
    let sql = plan.insert_sql();
    let mut stmt = c.statement(&sql).and_then(|b| b.build()).map_err(err)?;
    let array_rows = plan.array_rows();
    let mut pending: Vec<Vec<B>> = Vec::with_capacity(array_rows.min(ARRAY_ROWS));
    let mut pending_bytes = 0usize;
    let (mut since_rows, mut since_bytes, mut total) = (0u64, 0u64, 0u64);

    let commit = |since_rows: &mut u64, since_bytes: &mut u64, total: u64| -> Result<()> {
        // Held through the commit: the load's future can't be dropped
        // halfway through it.
        let closed = gate.0.lock().map_err(|_| poisoned())?;
        if *closed {
            return Err(Error::Cancelled);
        }
        c.commit().map_err(err)?;
        drop(closed);
        *since_rows = 0;
        *since_bytes = 0;
        let _ = committed.send(total);
        Ok(())
    };
    let execute = |stmt: &mut oracledb::Statement, pending: &mut Vec<Vec<B>>| -> Result<u64> {
        if gate.closed() {
            return Err(Error::Cancelled);
        }
        execute(stmt, pending)
    };

    while let Some(rows) = next()? {
        for mut row in rows {
            let mut bound = Vec::with_capacity(plan.cols.len());
            for col in &plan.cols {
                // Taken, not copied: the batch's memory becomes the binds'.
                let cell = row.get_mut(col.index).map_or(Cell::Null, |c| std::mem::replace(c, Cell::Null));
                bound.push(bind(cell, col, plan.native)?);
            }
            let bytes: usize = bound.iter().map(B::size).sum();
            if bound.iter().zip(&plan.cols).any(|(b, col)| b.is_big(col.lob)) {
                // Direct-path rows must be committed before a conventional
                // insert into the same table (ORA-12838).
                if plan.direct && !pending.is_empty() {
                    total += execute(&mut stmt, &mut pending)?;
                    pending_bytes = 0;
                    commit(&mut since_rows, &mut since_bytes, total)?;
                }
                insert_big(c, plan, bound)?;
                total += 1;
                since_rows += 1;
                since_bytes += bytes as u64;
                if plan.direct || since_rows >= plan.commit_rows || since_bytes >= plan.commit_bytes {
                    commit(&mut since_rows, &mut since_bytes, total)?;
                }
                continue;
            }
            pending.push(bound);
            pending_bytes += bytes;
            let window_full = since_rows + pending.len() as u64 >= plan.commit_rows || since_bytes + pending_bytes as u64 >= plan.commit_bytes;
            if pending.len() >= array_rows || pending_bytes >= ARRAY_BYTES || window_full {
                let n = execute(&mut stmt, &mut pending)?;
                total += n;
                since_rows += n;
                since_bytes += pending_bytes as u64;
                pending_bytes = 0;
                if plan.direct || since_rows >= plan.commit_rows || since_bytes >= plan.commit_bytes {
                    commit(&mut since_rows, &mut since_bytes, total)?;
                }
            }
        }
    }
    if !pending.is_empty() {
        let n = execute(&mut stmt, &mut pending)?;
        total += n;
        since_rows += n;
    }
    if since_rows > 0 || total == 0 {
        commit(&mut since_rows, &mut since_bytes, total)?;
    }
    Ok(total)
}

/// One array execute of the pending rows (emptied); the rows inserted.
fn execute(stmt: &mut oracledb::Statement, pending: &mut Vec<Vec<B>>) -> Result<u64> {
    let n = pending.len() as u64;
    {
        let rows: Vec<Vec<&dyn ToDbValue>> = pending.iter().map(|r| r.iter().map(B::as_dyn).collect()).collect();
        let slices: Vec<&[&dyn ToDbValue]> = rows.iter().map(Vec::as_slice).collect();
        stmt.execute_batch(slices.as_slice().into()).map_err(err)?;
    }
    pending.clear();
    Ok(n)
}

/// A row with a value too large for a bind (or an empty LOB): a PL/SQL
/// block builds each such value in a temporary LOB, 32 KB at a time, then
/// inserts the row.
fn insert_big(c: &Connection, plan: &Plan, row: Vec<B>) -> Result<()> {
    let mut decl = String::from("v VARCHAR2(32767); r RAW(32767); ");
    let mut body = String::new();
    let mut values = Vec::new();
    let mut params: Vec<B> = Vec::new();
    let mut free = String::new();
    for (i, (b, col)) in row.into_iter().zip(&plan.cols).enumerate() {
        if !b.is_big(col.lob) {
            params.push(b);
            values.push(col.kind.expr(&format!(":p{}", params.len()), plan.native));
            continue;
        }
        let l = format!("l{i}");
        match b {
            B::S(s) => {
                decl.push_str(&format!("{l} CLOB; "));
                body.push_str(&format!("DBMS_LOB.CREATETEMPORARY({l}, TRUE); "));
                for piece in utf8_pieces(&s, LOB_CHUNK) {
                    params.push(B::S(piece.to_string()));
                    // LENGTH2: a CLOB counts UTF-16 code units, so a
                    // character outside the BMP is 2 (LENGTH says 1).
                    body.push_str(&format!("v := :p{}; DBMS_LOB.WRITEAPPEND({l}, LENGTH2(v), v); ", params.len()));
                }
            }
            B::R(bytes) => {
                decl.push_str(&format!("{l} BLOB; "));
                body.push_str(&format!("DBMS_LOB.CREATETEMPORARY({l}, TRUE); "));
                for piece in bytes.chunks(LOB_CHUNK) {
                    params.push(B::R(piece.to_vec()));
                    body.push_str(&format!("r := :p{}; DBMS_LOB.WRITEAPPEND({l}, UTL_RAW.LENGTH(r), r); ", params.len()));
                }
            }
            _ => unreachable!("only text and bytes are big"),
        }
        values.push(col.kind.expr(&l, plan.native));
        free.push_str(&format!("DBMS_LOB.FREETEMPORARY({l}); "));
    }
    let names: Vec<String> = plan.cols.iter().map(|c| quote(&c.name)).collect();
    let block = format!(
        "DECLARE {decl}BEGIN {body}INSERT INTO {} ({}) VALUES ({}); {free}END;",
        plan.table,
        names.join(", "),
        values.join(", ")
    );
    // By name: the pieces' binds come before the INSERT's in the text.
    let names: Vec<String> = (1..=params.len()).map(|i| format!("P{i}")).collect();
    let named: Vec<(&str, &dyn ToDbValue)> = names.iter().map(String::as_str).zip(params.iter().map(B::as_dyn)).collect();
    let mut stmt = c.statement(&block).map(|b| b.exclude_from_cache()).and_then(|b| b.build()).map_err(err)?;
    stmt.execute_named(&named).map_err(err)?;
    Ok(())
}

/// `s` in pieces of at most `max` bytes, cut on character boundaries.
fn utf8_pieces(s: &str, max: usize) -> Vec<&str> {
    let mut out = Vec::new();
    let mut rest = s;
    while !rest.is_empty() {
        let mut end = rest.len().min(max);
        while !rest.is_char_boundary(end) {
            end -= 1;
        }
        out.push(&rest[..end]);
        rest = &rest[end..];
    }
    out
}

/// What a cell is, for an error message.
fn describe(cell: &Cell) -> String {
    match cell {
        Cell::Bytes(b) => format!("{} bytes", b.len()),
        Cell::Text(s) | Cell::Json(s) | Cell::Decimal(s) if s.len() > 60 => format!("un texto de {} caracteres", s.chars().count()),
        other => format!("{other:?}"),
    }
}

fn bad(cell: &Cell, col: &Col) -> Error {
    Error::Query(format!("Columna {}: no se puede convertir {} al tipo de la columna ({:?}).", col.name, describe(cell), col.kind))
}

/// A cell bound for its target column (taken: its text or bytes move into
/// the bind).
fn bind(cell: Cell, col: &Col, native: bool) -> Result<B> {
    if matches!(cell, Cell::Null) {
        return Ok(B::Null(col.kind.db_type()));
    }
    let b = match col.kind {
        Kind::Number => {
            let text = match &cell {
                Cell::Int(i) => Some(i.to_string()),
                Cell::UInt(u) => Some(u.to_string()),
                Cell::Bool(b) => Some((*b as u8).to_string()),
                Cell::Float(f) if f.is_finite() => plain_decimal(&format!("{f:e}")),
                Cell::Decimal(s) | Cell::Text(s) => plain_decimal(s.trim()),
                _ => None,
            };
            B::S(text.ok_or_else(|| bad(&cell, col))?)
        }
        Kind::Double => {
            let v = match &cell {
                Cell::Float(f) => Some(*f),
                Cell::Int(i) => Some(*i as f64),
                Cell::UInt(u) => Some(*u as f64),
                Cell::Bool(b) => Some(*b as u8 as f64),
                // "1e400" parses as infinity: only an explicit infinity is one.
                Cell::Decimal(s) | Cell::Text(s) => {
                    s.trim().parse::<f64>().ok().filter(|f| f.is_finite() || s.to_ascii_lowercase().contains("inf"))
                }
                _ => None,
            };
            B::F(v.ok_or_else(|| bad(&cell, col))?)
        }
        Kind::Bool => {
            let v = match &cell {
                Cell::Bool(b) => Some(*b),
                Cell::Int(i) => Some(*i != 0),
                Cell::UInt(u) => Some(*u != 0),
                Cell::Text(s) => match s.trim().to_ascii_lowercase().as_str() {
                    "1" | "true" | "t" | "y" | "yes" => Some(true),
                    "0" | "false" | "f" | "n" | "no" => Some(false),
                    _ => None,
                },
                _ => None,
            };
            B::Bool(v.ok_or_else(|| bad(&cell, col))?)
        }
        Kind::Raw => B::R(match cell {
            Cell::Bytes(b) => b,
            Cell::Uuid(s) => hex(&s.replace('-', "")).ok_or_else(|| bad(&Cell::Uuid(s.clone()), col))?,
            Cell::Text(s) => {
                let h = s.strip_prefix("0x").or_else(|| s.strip_prefix("0X"));
                match col.raw_text {
                    RawText::Hex => hex(h.unwrap_or(&s)).ok_or_else(|| bad(&Cell::Text(s.clone()), col))?,
                    RawText::Utf8 => s.into_bytes(),
                    RawText::Unknown => match h.and_then(hex) {
                        Some(b) => b,
                        None => s.into_bytes(),
                    },
                }
            }
            other => return Err(bad(&other, col)),
        }),
        Kind::Timestamp => {
            let t = match &cell {
                Cell::Date(s) | Cell::DateTime(s) | Cell::DateTimeTz(s) | Cell::Text(s) => parse_ts(s),
                Cell::Time(s) => parse_ts(&format!("1970-01-01 {s}")),
                _ => None,
            }
            .ok_or_else(|| bad(&cell, col))?;
            B::T(OracleTimestamp::new_timestamp(t.y, t.mo, t.d, t.h, t.mi, t.s, t.ns))
        }
        Kind::TimestampTz => match cell {
            // The native read's own text, with its region.
            Cell::Text(s) if native => B::S(s),
            Cell::Date(s) | Cell::DateTime(s) | Cell::DateTimeTz(s) | Cell::Text(s) => {
                B::S(parse_ts(&s).ok_or_else(|| bad(&Cell::Text(s.clone()), col))?.tz_text())
            }
            other => return Err(bad(&other, col)),
        },
        Kind::IntervalDs => B::S(match cell {
            Cell::Text(s) => s,
            Cell::Time(s) => format!("+0 {s}"),
            other => return Err(bad(&other, col)),
        }),
        Kind::IntervalYm => B::S(match cell {
            Cell::Text(s) => s,
            other => return Err(bad(&other, col)),
        }),
        Kind::Text | Kind::Json => B::S(match cell {
            Cell::Text(s) | Cell::Json(s) | Cell::Decimal(s) | Cell::Date(s) | Cell::Time(s) | Cell::DateTime(s) | Cell::DateTimeTz(s) | Cell::Uuid(s) => s,
            Cell::Int(i) => i.to_string(),
            Cell::UInt(u) => u.to_string(),
            Cell::Float(f) => f.to_string(),
            Cell::Bool(b) => (if b { "1" } else { "0" }).to_string(),
            Cell::Bytes(b) => b.iter().map(|x| format!("{x:02X}")).collect(),
            Cell::Null => unreachable!(),
        }),
    };
    // Oracle keeps no empty VARCHAR2 / CHAR / RAW (nor an empty interval
    // or JSON): the bind would be stored as NULL, or refused by NOT NULL.
    // Empty CLOBs and BLOBs are fine (see `B::is_big`).
    let empty = matches!(&b, B::S(s) if s.is_empty()) || matches!(&b, B::R(r) if r.is_empty());
    if empty && !col.lob {
        return Err(Error::Unsupported(format!(
            "Columna {}: Oracle guarda el texto vacío ('') y el binario vacío como NULL, así que no se puede copiar ese valor \
             sin cambiarlo. Convertí los vacíos a NULL (u otro valor) en el origen, o usá una columna CLOB / BLOB en el destino.",
            col.name
        )));
    }
    Ok(b)
}

fn hex(s: &str) -> Option<Vec<u8>> {
    if !s.len().is_multiple_of(2) || !s.bytes().all(|b| b.is_ascii_hexdigit()) {
        return None;
    }
    (0..s.len()).step_by(2).map(|i| u8::from_str_radix(&s[i..i + 2], 16).ok()).collect()
}

/// A decimal number as plain digits (`1.5e-3` → `0.0015`), `None` when it
/// isn't a number or is outside NUMBER's range (so the text never grows
/// past the input plus 130 digits).
fn plain_decimal(s: &str) -> Option<String> {
    let (neg, body) = match s.strip_prefix('-') {
        Some(r) => (true, r),
        None => (false, s.strip_prefix('+').unwrap_or(s)),
    };
    let (mant, exp) = match body.find(['e', 'E']) {
        Some(i) => (&body[..i], body[i + 1..].parse::<i64>().ok()?),
        None => (body, 0),
    };
    let (int, frac) = mant.split_once('.').unwrap_or((mant, ""));
    if int.is_empty() && frac.is_empty() || !int.bytes().chain(frac.bytes()).all(|b| b.is_ascii_digit()) {
        return None;
    }
    let digits = format!("{int}{frac}");
    let significant = digits.trim_start_matches('0');
    if significant.is_empty() {
        return Some("0".into());
    }
    // Where the point goes, counted from the first digit, then from the
    // first significant one (the value is 0.significant × 10^magnitude).
    let point = (int.len() as i64).checked_add(exp)?;
    let magnitude = point - (digits.len() - significant.len()) as i64;
    if !(NUMBER_MIN_MAGNITUDE..=NUMBER_MAX_MAGNITUDE).contains(&magnitude) {
        return None;
    }
    let digits = significant;
    let point = magnitude;
    let mut out = String::new();
    if point <= 0 {
        out.push_str("0.");
        out.extend(std::iter::repeat_n('0', (-point) as usize));
        out.push_str(digits);
    } else if point as usize >= digits.len() {
        out.push_str(digits);
        out.extend(std::iter::repeat_n('0', point as usize - digits.len()));
    } else {
        out.push_str(&digits[..point as usize]);
        out.push('.');
        out.push_str(&digits[point as usize..]);
    }
    let out = if out.contains('.') { out.trim_end_matches('0').trim_end_matches('.').to_string() } else { out };
    let out = out.trim_start_matches('0');
    let out = if out.is_empty() || out.starts_with('.') { format!("0{out}") } else { out.to_string() };
    Some(if neg && out != "0" { format!("-{out}") } else { out })
}

/// A parsed date-time.
#[derive(Debug, Clone, Copy, PartialEq)]
struct Ts {
    /// Oracle's year: negative is BC (-1 is 1 BC; there is no year 0).
    y: i16,
    mo: u8,
    d: u8,
    h: u8,
    mi: u8,
    s: u8,
    ns: u32,
    /// Offset in minutes.
    tz: Option<i32>,
}

impl Ts {
    /// For `TO_TIMESTAMP_TZ(…, TZ_FORMAT)`; no offset means UTC.
    fn tz_text(&self) -> String {
        let off = self.tz.unwrap_or(0);
        let sign = if off < 0 { '-' } else { '+' };
        format!(
            "{}{:04}-{:02}-{:02} {:02}:{:02}:{:02}.{:09} {sign}{:02}:{:02}",
            if self.y < 0 { "-" } else { "" },
            self.y.unsigned_abs(),
            self.mo,
            self.d,
            self.h,
            self.mi,
            self.s,
            self.ns,
            off.abs() / 60,
            off.abs() % 60
        )
    }
}

/// `YYYY-MM-DD[( |T)HH:MM[:SS[.f]]][ ][Z|±HH[:MM]][ BC]`.
fn parse_ts(s: &str) -> Option<Ts> {
    let mut s = s.trim();
    let bc = s.len() > 3 && s[s.len() - 3..].eq_ignore_ascii_case(" bc");
    if bc {
        s = s[..s.len() - 3].trim_end();
    }
    let num = |t: &str| -> Option<u32> { (!t.is_empty() && t.bytes().all(|b| b.is_ascii_digit())).then(|| t.parse().ok()).flatten() };
    let date = s.get(..10)?;
    let mut parts = date.split('-');
    let (y, mo, d) = (num(parts.next()?)?, num(parts.next()?)?, num(parts.next()?)?);
    // Oracle's years: 4712 BC to 9999 AD, no year 0.
    if !(1..=12).contains(&mo) || !(1..=31).contains(&d) || y > 9999 || y == 0 || bc && y > 4712 {
        return None;
    }
    let y = if bc { -(y as i16) } else { y as i16 };
    let mut t = Ts { y, mo: mo as u8, d: d as u8, h: 0, mi: 0, s: 0, ns: 0, tz: None };
    let mut rest = &s[10..];
    if let Some(r) = rest.strip_prefix([' ', 'T']) {
        let end = r.find(|c: char| !(c.is_ascii_digit() || c == ':' || c == '.')).unwrap_or(r.len());
        let (time, tail) = r.split_at(end);
        let (hms, frac) = time.split_once('.').unwrap_or((time, ""));
        let mut f = hms.split(':');
        t.h = num(f.next()?)? as u8;
        t.mi = num(f.next()?)? as u8;
        t.s = f.next().map(num).unwrap_or(Some(0))? as u8;
        if f.next().is_some() || t.h > 23 || t.mi > 59 || t.s > 60 {
            return None;
        }
        if !frac.is_empty() {
            let digits: String = frac.chars().take(9).collect();
            t.ns = num(&digits)? * 10u32.pow(9 - digits.len() as u32);
        }
        rest = tail;
    }
    let rest = rest.trim_start();
    if rest.is_empty() {
        return Some(t);
    }
    if rest == "Z" || rest == "z" {
        t.tz = Some(0);
        return Some(t);
    }
    let sign = match rest.as_bytes()[0] {
        b'+' => 1,
        b'-' => -1,
        _ => return None,
    };
    let off = rest[1..].replace(':', "");
    let (h, m) = match off.len() {
        2 => (num(&off)?, 0),
        4 => (num(&off[..2])?, num(&off[2..])?),
        _ => return None,
    };
    t.tz = Some(sign * (h as i32 * 60 + m as i32));
    Some(t)
}

// ------------------------------------------------------------ native copy

fn oracle(s: &mut dyn Session) -> Option<&mut OracleSession> {
    s.as_any()?.downcast_mut::<OracleSession>()
}

/// The native read's end: batches (then `None`) to the load.
struct NativeSink {
    tx: tokio::sync::mpsc::Sender<Option<RowBatch>>,
}

impl BatchSink for NativeSink {
    fn begin(&mut self, _columns: &[TransferColumn]) -> std::io::Result<()> {
        Ok(())
    }

    fn batch(&mut self, batch: RowBatch) -> std::io::Result<()> {
        // On the read's blocking thread: waits while the load is behind.
        self.tx.blocking_send(Some(batch)).map_err(|_| std::io::Error::other("se detuvo la escritura en el destino"))
    }
}

/// The load's end. If the read goes away without `None` (it failed) this
/// never returns: the copy ends through the read's error.
struct NativeSource {
    rx: tokio::sync::mpsc::Receiver<Option<RowBatch>>,
}

#[dbine_driver::async_trait]
impl BatchSource for NativeSource {
    async fn next(&mut self) -> Option<RowBatch> {
        match self.rx.recv().await {
            Some(batch) => batch,
            None => std::future::pending().await,
        }
    }
}

/// Oracle to Oracle: the read and the load above, joined by a channel of
/// [`NATIVE_BATCHES`], with time zone regions and extended JSON kept (see
/// the module's docs). The source only runs a `SELECT`.
pub(crate) async fn copy_native(source: &mut dyn Session, target: &mut dyn Session, spec: &CopySpec, progress: Progress<'_>) -> Result<u64> {
    let (Some(src), Some(dst)) = (oracle(source), oracle(target)) else {
        return Err(Error::Unsupported("copia directa no disponible: las sesiones no son de Oracle".into()));
    };
    let (tx, rx) = tokio::sync::mpsc::channel(NATIVE_BATCHES);
    let end = tx.clone();
    let sink: BatchSinkRef = Arc::new(Mutex::new(NativeSink { tx }));
    let reader = async move {
        let n = read_with(src, &spec.source, sink, true).await?;
        end.send(None).await.map_err(|_| Error::State("se detuvo la escritura en el destino".into()))?;
        Ok::<_, Error>(n)
    };
    let mut from = NativeSource { rx };
    let writer = load_with(dst, &spec.target, &[], &mut from, progress, true);
    tokio::pin!(reader);
    tokio::pin!(writer);
    tokio::select! {
        r = &mut reader => {
            // A failed read drops the load: nothing of it stays committed.
            r?;
            writer.await
        }
        w = &mut writer => {
            // The load ends only after the read's `None`, or with an error;
            // on an error the read stops at its next batch (the channel is
            // closed when this returns).
            let n = w?;
            reader.await?;
            Ok(n)
        }
    }
}

